/* Vertical slice: inspeção sensitiva → achado → notificação distinta da OS. */
'use strict';
const assert=require('node:assert/strict');
const I=require('../phaser-play/inspection.js');
const E=require('../engine.js');
const data=require('../game-data.json');
const s=E.create(data,()=>0.4),originalJobs=JSON.stringify(s.jobs),originalNextJob=s.nextJob;
I.normalized(s);
let rounds=I.plan(s,data);
assert.equal(rounds.length,3,'três inspeções planejadas no primeiro turno');
assert.equal(I.plan(s,data)[0].id,rounds[0].id,'planejamento idempotente');
assert.equal(s.inspections.length,3);
assert.ok(rounds.every(x=>x.status==='pending'&&!s.jobs.some(j=>j.asset===x.asset)),'máquinas livres de OS');
const a=I.inspect(s,data,rounds[0].id);
assert.equal(a.ok,true);assert.equal(a.status,'finding','primeiro indício didático');
assert.equal(I.inspect(s,data,rounds[0].id).error!==undefined,true,'sem reinspeção no turno');
assert.equal(I.notify(s,rounds[0].id,'curto','alta').error!==undefined,true,'descrição insuficiente');
assert.equal(I.notify(s,rounds[0].id,'Ruído ou alteração durante a operação','urgente').error!==undefined,true,'prioridade inválida');
const n=I.notify(s,rounds[0].id,'Condição sensitiva irregular registrada para revisão do PCM.','alta');
assert.equal(n.ok,true);
assert.equal(s.notifications[0].id,'NM0001');
assert.equal(s.notifications[0].status,'aguarda_revisao_pcm');
assert.equal(s.notifications[0].workOrderId,null,'sem criação automática de OS');
assert.equal(s.notifications[0].evidenceType,'observacao_simulada');
assert.equal(I.notify(s,rounds[0].id,'Nova descrição para a mesma ocorrência','alta').error!==undefined,true,'notificação única');
assert.equal(JSON.stringify(s.jobs),originalJobs,'OS originais intactas');
assert.equal(s.nextJob,originalNextJob,'sequência de OS intacta');
const other=I.inspect(s,data,rounds[2].id);
assert.equal(other.status,'clear','outro resultado sensitivo possível');
assert.equal(I.notify(s,rounds[2].id,'Tentativa de abrir notificação sobre item normal','baixa').error!==undefined,true);
const clone=JSON.parse(JSON.stringify(s));I.normalized(clone);
assert.deepEqual(clone,s,'save compatível e normalização idempotente');
s.tick++;s.shift=1;
rounds=I.plan(s,data);
assert.equal(rounds.length,3);
assert.equal(s.inspections.length,6);
assert.equal(s.inspections.find(x=>x.id==='IN0002').status,'expired','não inspecionadas vencem');
assert.ok(rounds.every(x=>x.tick===1&&!s.jobs.some(j=>j.asset===x.asset)));
const imported=JSON.parse(JSON.stringify({version:'1.1.0',tick:12,jobs:[],inspections:[{id:'IN0033',tick:1}],notifications:[{id:'NM0009'}]}));
I.normalized(imported);
assert.equal(imported.nextInspection,34);assert.equal(imported.nextNotification,10);
const fs=require('node:fs'),path=require('node:path');
const game=fs.readFileSync(path.join(__dirname,'../phaser-play/game.js'),'utf8');
const html=fs.readFileSync(path.join(__dirname,'../phaser-play/index.html'),'utf8');
assert.ok(game.includes('I.plan(state,data)'),'planejamento integrado');
const view=fs.readFileSync(path.join(__dirname,'../phaser-play/inspection-view.js'),'utf8');
assert.ok(view.includes('data-inspection-action="inspect"')&&view.includes('data-inspection-action="notify"'),'ações de inspeção e notificação');
assert.ok(html.includes('data-panel="inspection"')&&html.includes('data-open-panel="inspection"'),'painel acessível');
assert.ok(html.includes('inspection.js?v=0.9.0'),'script versionado');
console.log('OK: inspeções por turno, evidência simulada, notificações separadas, saves antigos e UI.');
