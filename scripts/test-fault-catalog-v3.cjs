/* Catálogo eletrônico v3: 18 sinais novos, estados ET e integridade da rota PCM. */
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const D=require('../game-data.json'),E=require('../engine.js'),I=require('../phaser-play/inspection.js');
const C=require('../phaser-play/condition-catalog.js'),M=require('../phaser-play/monitoring.js');
const S=require('../phaser-play/sector-views.js'),V=require('../phaser-play/inspection-view.js');
const F=require('../phaser-play/fault-catalog-expansion.js');
assert.equal(F.VERSION,'3.0.0');
assert.equal(C.VERSION,'6.0.0');
assert.equal(F.ENTRIES.length,18);
assert.equal(C.ENTRIES.length,120);
assert.deepEqual(Object.fromEntries(['oil','faults','undercarriage','fps','components'].map(k=>[k,C.byCategory(k).length])),
 {oil:24,faults:24,undercarriage:24,fps:24,components:24});
assert.equal(new Set(C.ENTRIES.map(x=>x.id)).size,120,'ids imutáveis');
assert.ok(C.get('OIL023')&&C.get('FPS001')&&C.get('CMP005'),'catálogos anteriores preservados');
const ids=new Set(F.ENTRIES.map(x=>x.id));
assert.equal(ids.size,18,'sinais novos distintos');
for(let i=1;i<=24;i++){
 const id='FLT'+String(i).padStart(3,'0'),e=C.get(id);
 assert.ok(e&&e.category==='faults',id+' deve existir');
 assert.ok(e.baseline.length>60&&e.title.length>22,id+' com observação adequada');
 assert.ok(['diagnostico','evento'].includes(e.signalClass),id+' classe ET');
 assert.ok(['ativo','registrado','nao_confirmado'].includes(e.codeState),id+' estado não confundido com intermitência');
 assert.ok(e.codeValue===null&&e.codeVerified===false,id+' não atribuir numeração inventada');
 assert.ok(e.moduleContext.length>20&&e.observedEffect.length>15,id+' módulo e efeito');
 assert.ok(e.verification.length>60&&e.uncertainty.length>30,id+' procedimento e limitação');
 assert.ok(e.alternatives.length===3,'alternativas investigativas sem gabarito');
 assert.ok(Object.isFrozen(e.alternatives),'alternativas imutáveis');
 assert.ok(e.sourceKeys.every(k=>/^https:\/\/www\.cat\.com\//.test(C.SOURCES[k]||'')),'fontes oficiais rastreáveis');
 assert.ok(Object.hasOwn(D.tools,e.followupTool),'ferramental cadastrado');
 assert.equal(e.followupCost,0,'verificação eletrônica não cobra amostra de óleo');
 assert.ok(!e.escalationScenario||D.scenarios.some(x=>x.id===e.escalationScenario&&x.modelId===e.modelId),id+' FMEA existente compatível');
 assert.ok(['acompanhar','avaliacao_prioritaria'].includes(e.triage));
}
assert.ok(['FLT022','FLT023','FLT024'].every(id=>C.get(id).escalationScenario===null),'códigos sem roteiro não inventam FMEA');
assert.equal(C.get('FLT020').signalClass,'evento');
assert.equal(C.get('FLT021').codeState,'registrado');
assert.equal(C.get('FLT008').codeState,'nao_confirmado','intermitência != estado ativo');
assert.equal(C.get('FLT008').pattern,'intermitente');
const fresh=()=>{const s=E.create(D,()=>.5);I.normalized(s);return s;};
function receiveOne(id){
 const s=fresh();s.monitoringFeedCursor=1;s.monitoringFeedSeen=C.byCategory('faults').filter(x=>x.id!==id).map(x=>x.id);
 const r=M.receive(s,D,I,{initial:true});
 assert.equal(r.received.length,1,id+' recebe evento automaticamente');
 const n=r.received[0];assert.equal(n.monitorProtocol,id);
 assert.equal(n.monitorCategory,'faults');
 assert.equal(n.inspectionId,null);
 assert.equal(n.sourceScenario,null);
 assert.equal(n.workOrderId,null);
 return {s,n};
}
const urgent=receiveOne('FLT023');
assert.equal(urgent.n.priority,'alta');
assert.ok(M.decide(urgent.s,urgent.n.id,'trend',2).error,'não permite adiar triagem prioritária');
const urgentCard=V.monitorWidget(urgent.n,urgent.s,M);
assert.ok(urgentCard.includes('AVALIAÇÃO PRIORITÁRIA')&&urgentCard.includes('ENCAMINHAR AO PCM'));
assert.ok(urgentCard.includes('EVENTO OPERACIONAL')&&urgentCard.includes('ATIVO'));
assert.ok(urgentCard.includes('Código OEM:</strong> NÃO INFORMADO'));
const beforeUrgentJobs=urgent.s.jobs.length,raised=M.escalate(urgent.s,D,I,urgent.n.id);
assert.equal(raised.ok,true);
assert.equal(raised.escalation.sourceScenario,null,'não vincular evento genérico a falha não documentada');
assert.equal(raised.escalation.requiresScenarioMapping,true);
assert.equal(raised.escalation.priority,'alta');
assert.equal(urgent.s.jobs.length,beforeUrgentJobs,'nenhuma OS automática');
assert.ok(I.review(urgent.s,raised.escalation.id,'approve',{},D,E).error,'PCM não usa gabarito inexistente');
const mapped=receiveOne('FLT011');
assert.equal(M.escalate(mapped.s,D,I,mapped.n.id).escalation.sourceScenario,'INC050','FMEA existente recuperado');
assert.equal(mapped.s.jobs.length,3,'não converter automaticamente');
const logged=receiveOne('FLT021');
const loggedCard=V.monitorWidget(logged.n,logged.s,M);
assert.ok(loggedCard.includes('REGISTRADO')&&loggedCard.includes('NÃO INFORMADO'));
assert.ok(!loggedCard.includes('AVALIAÇÃO PRIORITÁRIA'),'histórico sem sintoma atual não é urgência automática');
assert.equal(M.decide(logged.s,logged.n.id,'sample',2).ok,true);
logged.s.tools.SCAN=true;logged.s.tick+=2;
assert.equal(M.collect(logged.s,logged.n.id).sample.trend,'estavel');
assert.equal(M.continueWatch(logged.s,logged.n.id,2).ok,true);
logged.s.tick+=2;
assert.equal(M.collect(logged.s,logged.n.id).sample.trend,'estavel');
assert.equal(M.close(logged.s,logged.n.id).ok,true);
const comm=receiveOne('FLT015');
assert.equal(M.decide(comm.s,comm.n.id,'trend',2).ok,true);
comm.s.tick+=2;comm.s.tools.CAN=false;
assert.ok(M.collect(comm.s,comm.n.id).error,'CAN é necessário para verificação simulada');
comm.s.tools.CAN=true;
assert.equal(M.collect(comm.s,comm.n.id).sample.trend,'inconclusivo');
const faultsView=S.monitoring(fresh(),D,M,V,I,E,'faults');
assert.ok(faultsView.includes('24 ENTRADAS')&&faultsView.includes('FLT024'));
assert.ok(faultsView.includes('Código OEM: NÃO INFORMADO'));
assert.ok(!faultsView.includes('OIL023'),'categoria não mistura fluidos');
const overall=S.monitoring(fresh(),D,M,V,I,E,'overview');
assert.ok(overall.includes('FLT023')&&overall.includes('OIL023')&&overall.includes('CMP001'));
const html=fs.readFileSync('phaser-play/index.html','utf8');
assert.ok(html.indexOf('fault-catalog-expansion.js')<html.indexOf('condition-catalog.js'),'ordem do carregamento');
assert.ok(html.includes('inspection-view.js?v=0.9.8')&&html.includes('sector-views.js?v=0.9.8'));
const sw=fs.readFileSync('sw.js','utf8');
assert.ok(sw.includes("'./phaser-play/fault-catalog-expansion.js'"));
assert.ok(sw.includes('fault096'));
assert.equal(E.validate(JSON.parse(JSON.stringify(logged.s))),true,'saves válidos');
console.log('OK: 64 sintomas; 24 registros eletrônicos, estados, ECM, ausência de código, PCM e saves.');
