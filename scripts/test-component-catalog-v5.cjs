const fresh=()=>{const s=E.create(D,()=>.5);I.normalized(s);return s};
function receive(id){
 const s=fresh();s.monitoringFeedCursor=4;s.monitoringFeedSeen=C.byCategory('components').filter(p=>p.id!==id).map(p=>p.id);
 const r=M.receive(s,D,I,{initial:true});
 assert.equal(r.received.length,1,id+' chegada automática');
 const n=r.received[0];assert.equal(n.monitorProtocol,id);assert.equal(n.monitorCategory,'components');
 assert.equal(n.sourceScenario,null);assert.equal(n.workOrderId,null);assert.equal(n.inspectionId,null);
 return {s,n};
}
const urgent=receive('CMP024');
assert.equal(urgent.n.priority,'alta');
const card=V.monitorWidget(urgent.n,urgent.s,M);
assert.ok(card.includes('AVALIAÇÃO PRIORITÁRIA'));
assert.ok(card.includes('Sistema/componente:'));
assert.ok(card.includes('Hipóteses concorrentes'));
assert.ok(card.includes('Medida / referência OEM:'));
assert.ok(!card.includes('data-monitor-action="decide"'));
assert.ok(M.decide(urgent.s,urgent.n.id,'trend',2).error,'não adiar condição prioritária');
const count=urgent.s.jobs.length;
const es=M.escalate(urgent.s,D,I,urgent.n.id);
assert.equal(es.ok,true);assert.equal(es.escalation.requiresScenarioMapping,true);
assert.equal(es.escalation.sourceScenario,null);assert.equal(urgent.s.jobs.length,count);
assert.ok(I.review(urgent.s,es.escalation.id,'approve',{},D,E).error,'sem roteiro não se gera OS');
