/* Regression: 0.8.4 ships the exact official night workshop to GitHub Pages. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const root=path.join(__dirname,'..');
const night=path.join(root,'phaser-play','assets','oficina-noturna-hq.avif');
const day=path.join(root,'phaser-play','assets','oficina-base.avif');
const b=fs.readFileSync(night);
assert.equal(b.length,160249,'optimized night asset file size');
assert.equal(crypto.createHash('sha256').update(b).digest('hex'),
'0637e55b3a1978842c7aa71e27c763b176ea7c8438a82ee5bc711140e1a72c15','night asset SHA-256 matches original archived copy');
assert.equal(b.toString('ascii',4,8),'ftyp','AVIF ISOBMFF header');
assert.equal(b.toString('ascii',8,12),'avif','AVIF compatible brand');
const at=b.indexOf(Buffer.from('ispe'));
assert.ok(at>=0,'AVIF spatial extent box exists');
assert.equal(b.readUInt32BE(at+8),1976,'original full-frame width');
assert.equal(b.readUInt32BE(at+12),796,'original full-frame height');
assert.ok(fs.existsSync(day),'existing cropped day workshop remains');
const html=fs.readFileSync(path.join(root,'phaser-play','index.html'),'utf8');
const game=fs.readFileSync(path.join(root,'phaser-play','game.js'),'utf8');
const map=JSON.parse(fs.readFileSync(path.join(root,'phaser-play','scene-map.json'),'utf8'));
const manifest=fs.readFileSync(path.join(root,'phaser-play','assets','OFICINA-NOTURNA.md'),'utf8');
assert.ok(html.includes('game.js?v=0.8.25'),'entrypoint updated for browser cache');
assert.ok(html.includes('id="sceneState"'),'current background source is visible to user');
assert.ok(html.includes('Substituir noite (opcional)'),'local night override described as optional');
assert.ok(html.includes('Restaurar noite oficial'),'night reset returns to repository asset');
assert.ok(html.includes('dia e noite')||html.includes('Turno B = noite'),'user help explains automatic alternation');
assert.ok(game.includes("this.load.image('repoNightWorkshopBG','./assets/oficina-noturna-hq.avif?v=0.8.4')"),'Phaser preloads official local night asset');
assert.ok(game.includes("const key=night&&this.textures.exists('repoNightWorkshopBG')?'repoNightWorkshopBG'"),'native day/night switch without manual upload');
assert.ok(game.includes("if(night&&this.nightBackdropImage){this.setBackdrop(this.nightBackdropImage,'fullFrame');return}"),'user night override still takes priority');
assert.ok(game.includes("if(this.customBackdrop)return;"),'global custom override retains highest priority');
assert.ok(game.includes("this.setBackdrop(img,key==='repoWorkshopBG'?'cropped':'fullFrame')"),'both official backgrounds share fullFrame geometry');
assert.ok(game.includes('else if(night&&scene?.textures?.exists(\'repoNightWorkshopBG\'))'),'correct night source shown in menu');
assert.ok(game.includes("if(night&&key!=='repoNightWorkshopBG'&&this.backdrop)this.backdrop.setTint("),'browser fallback remains if night decoding fails');
assert.equal(map.backgroundProfiles.fullFrame.sourceReference.width,1976,'full-frame geometry original width');
assert.equal(map.backgroundProfiles.fullFrame.sourceReference.height,796,'full-frame geometry original height');
assert.deepEqual(map.backgroundProfiles.fullFrame.bays.map(x=>x.placementWorld.groundY),[408,408,408],'night does not move machines from approved floor');
assert.ok(manifest.includes('0637e55b3a1978842c7aa71e27c763b176ea7c8438a82ee5bc711140e1a72c15'),'source manifest records exact asset');
assert.ok(!manifest.includes('ainda não versionada como arquivo binário em `main`'),'night manifest no longer reports missing binary');
console.log('OK: official night AVIF 1976×796 SHA-256, preload, automatic day/night, override precedence and geometry.');
