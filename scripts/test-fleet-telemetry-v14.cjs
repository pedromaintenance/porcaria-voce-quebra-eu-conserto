/* PORCARIA / Ciclo 14: horímetros virtuais, disponibilidade e MTBF observável. */
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const D=require('../game-data.json'),E=require('../engine.js');
const F=require('../phaser-play/fleet-telemetry.js'),VIEW=require('../phaser-play/fleet-view.js');
assert.equal(F.VERSION,'14.0.0');
assert.equal(F.assetIDs(D).length,54);
const s=E.create(D,()=>0.45);
assert.equal(s.fleetTelemetry.startedTick,0);
assert.equal(s.fleetTelemetry.throughTick,0);
assert.equal(Object.keys(s.fleetTelemetry.assets).length,54);
assert.equal(s.fleetTelemetry.samples.length,0);
assert.equal(F.compute(s,D).metrics.operationalAvailabilityPct,null);
assert.equal(s.jobs.length,3);
assert.equal(s.jobs.reduce((n,j)=>n+s.fleetTelemetry.assets[j.asset].failures.length,0),3,'três ocorrências de abertura instrumentadas');
const job0=s.jobs[0];
assert.equal(F.failure(s,D,job0,'random'),null,'não duplicar evento de falha');
assert.equal(F.failure(s,D,{id:'MANUAL',asset:job0.asset},'manual'),null,'conversão manual não se torna falha automaticamente');
const free=F.assetIDs(D).find(id=>!s.jobs.some(j=>j.asset===id));
assert.ok(free);
const oldCash=s.cash;
assert.equal(E.bookPreventive(s,D,free,s.team[0].id,0,'service'),null);
const report=F.compute(s,D);
assert.equal(report.assets.find(a=>a.asset===free).currentState,'preventive');
assert.equal(report.assets.find(a=>a.asset===job0.asset).currentState,'corrective');
const before=JSON.stringify(s);
assert.equal(F.compute(s,D).metrics.mtbfHours,null);
assert.equal(JSON.stringify(s),before,'relatório não modifica estado');
E.advance(s,D,()=>0.9);
assert.equal(s.tick,1);
assert.equal(s.cash,oldCash-360,'serviço preventivo foi debitado no jogo');
const f=s.fleetTelemetry,first=f.samples[0];
assert.equal(first.tick,0);
assert.deepEqual([first.operating,first.corrective,first.preventive],[608,36,4]);
assert.equal(first.operating+first.corrective+first.preventive,54*12);
assert.equal(f.throughTick,1);
const row=f.assets[free];
assert.equal(row.hourmeter,8);
assert.equal(row.preventiveDown,4);
assert.equal(row.correctiveDown,0);
assert.equal(f.assets[job0.asset].correctiveDown,12);
assert.equal(f.assets[job0.asset].hourmeter,0);
const m=F.compute(s,D,{days:7});
assert.equal(m.metrics.trackedAssets,54);
assert.equal(m.metrics.operationalAvailabilityPct,93.8);
assert.equal(m.metrics.maintenanceAvailabilityPct,94.4);
assert.equal(m.metrics.theoreticalHours,648);
assert.equal(m.coverage.sampledTicks,1);
assert.equal(m.coverage.complete,false,'não declarar janela de 7 dias completa após um turno');
assert.ok(VIEW.render(m,'EQ01').includes('HORÍMETROS VIRTUAIS'));
assert.equal(F.failure(s,D,{id:'VIRTUAL001',asset:free},'random').hourmeter,8);
E.advance(s,D,()=>0.95);
assert.equal(s.tick,2);
assert.equal(f.assets[free].hourmeter,20);
assert.equal(F.failure(s,D,{id:'VIRTUAL002',asset:free},'progression').hourmeter,20);
const final=F.compute(s,D,{days:14});
const asset=final.assets.find(x=>x.asset===free);
assert.equal(asset.mtbfHours,12);
assert.equal(asset.validIntervals,1);
assert.equal(final.metrics.mtbfIntervals,1);
assert.equal(final.metrics.mtbfHours,12);
assert.equal(final.metrics.failureEvents>=5,true);
assert.equal(JSON.stringify(s),JSON.stringify(JSON.parse(JSON.stringify(s))),'telemetria serializável');
assert.equal(E.validate(JSON.parse(JSON.stringify(s))),true);
const legacy=E.create(D,()=>0.4);
delete legacy.fleetTelemetry;legacy.tick=20;legacy.day=11;legacy.shift=0;
assert.equal(E.validate(legacy),true);
E.initFleet(legacy,D);
assert.equal(legacy.fleetTelemetry.startedTick,20);
assert.equal(legacy.fleetTelemetry.samples.length,0);
assert.equal(legacy.fleetTelemetry.assets[legacy.jobs[0].asset].failures.length,0,'falhas preexistentes não fabricadas');
assert.equal(F.compute(legacy,D).metrics.mtbfHours,null);
E.advance(legacy,D,()=>0.9);
assert.equal(legacy.fleetTelemetry.samples.length,1);
assert.equal(legacy.fleetTelemetry.samples[0].tick,20);
assert.equal(legacy.fleetTelemetry.startedTick,20,'migração idempotente');
const prior=JSON.stringify(legacy);E.initFleet(legacy,D);assert.equal(JSON.stringify(legacy),prior);
const probe=JSON.parse(JSON.stringify(legacy));
const once=F.advance(probe,D);
assert.ok(!once.error,'a primeira leitura do turno corrente deve ser válida');
const twice=F.advance(probe,D);
assert.ok(twice.error,'não permitir segunda leitura do mesmo turno');
const game=fs.readFileSync('phaser-play/game.js','utf8'),sw=fs.readFileSync('sw.js','utf8');
assert.ok(game.includes("await import('./fleet-telemetry.js?v=0.9.17')"));
assert.ok(game.includes("await import('./fleet-view.js?v=0.9.17')"));
assert.ok(game.includes('E.initFleet(state,data)'));
assert.ok(game.includes('PORCARIA_FLEET_VIEW.render'));
assert.ok(sw.includes('fleet0917')&&sw.includes("'./phaser-play/fleet-telemetry.js'"));
console.log('OK v14: 54 horímetros, MTBF virtual com pares, disponibilidade, estados, PM/CM e migração.');
