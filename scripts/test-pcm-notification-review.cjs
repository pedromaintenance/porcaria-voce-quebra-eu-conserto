/* Regressão Fase 2: inspeção → notificação → revisão PCM → OS planejável. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const E=require('../engine.js');
const I=require('../phaser-play/inspection.js');
const V=require('../phaser-play/inspection-view.js');
const P=require('../phaser-play/planning.js');
const data=require('../game-data.json');
const s=E.create(data,()=>.42);
const originalJobs=JSON.stringify(s.jobs),originalCount=s.jobs.length,initialNext=s.nextJob;
const inspections=I.plan(s,data);
const first=inspections[0];
assert.equal(I.inspect(s,data,first.id).status,'finding');
const note=I.notify(s,first.id,'Indício de ruído anormal na região hidráulica.','alta').notification;
assert.ok(note);
assert.equal(note.status,'aguarda_revisao_pcm');
const reference=note.id;
const baseline=JSON.stringify(s.jobs);
assert.ok(I.review(s,reference,'return',{reason:'curta'}).error,'devolução requer justificativa');
assert.ok(I.review(s,reference,'approve',{scope:'curto',trade:'mecanica',estimatedHH:2}).error,'escopo insuficiente');
assert.ok(I.review(s,reference,'approve',{scope:'Verificar origem do ruído em segurança e registrar a condição.',trade:'falsa',estimatedHH:2}).error,'disciplina inválida');
assert.ok(I.review(s,reference,'approve',{scope:'Verificar origem do ruído em segurança e registrar a condição.',trade:'mecanica',estimatedHH:99}).error,'HH fora da faixa');
assert.ok(I.convert(s,data,reference).error,'sem OS antes da aprovação');
assert.equal(JSON.stringify(s.jobs),baseline,'nada alterado nas OS sem revisão aprovada');
let r=I.review(s,reference,'return',{reason:'Relato incompleto: identificar situação operacional e localização do ruído.'});
assert.equal(r.status,'devolvida');
assert.equal(I.summary(s).returned,1);
assert.ok(I.review(s,reference,'approve',{scope:'Inspecionar a máquina e documentar a anormalidade com evidências.',trade:'mecanica',estimatedHH:2}).error,'devolução bloqueia aprovação');
assert.ok(I.review(s,reference,'resubmit',{description:'curto',priority:'alta'}).error,'valida texto reaberto');
assert.equal(I.review(s,reference,'resubmit',{description:'Ruído durante carregamento, piora progressiva sob carga; não há medições.',priority:'media'}).status,'aguarda_revisao_pcm');
assert.equal(note.priority,'media');
const beforeApproved=JSON.stringify(s.jobs);
r=I.review(s,reference,'approve',{scope:'Inspecionar o circuito hidráulico sem presumir falha de bomba; registrar resultados e testes.',trade:'hidraulica',estimatedHH:4.5,reason:'Prioridade revisada conforme descrição do inspetor.'});
assert.equal(r.status,'aprovada_pcm');
assert.equal(note.planningScope.estimatedHH,4.5);
assert.equal(note.planningScope.trade,'hidraulica');
assert.equal(I.summary(s).approved,1);
assert.equal(JSON.stringify(s.jobs),beforeApproved,'aprovação não cria OS');
assert.equal(s.nextJob,initialNext,'sequência de OS preservada antes da conversão');
const duplicate={id:'OSFAKE',asset:first.asset};s.jobs.push(duplicate);
const countBeforeBlocked=s.jobs.length;
assert.ok(I.commitConversion(s,data,E,reference).error,'bloqueia OS duplicada por equipamento');
assert.equal(s.jobs.length,countBeforeBlocked);
assert.equal(note.status,'aprovada_pcm');
s.jobs.pop();
r=I.commitConversion(s,data,E,reference);
assert.equal(r.ok,true);
assert.equal(s.jobs.length,originalCount+1);
assert.equal(s.nextJob,initialNext+1);
const order=r.order;
assert.equal(order.id,'OS'+String(initialNext).padStart(4,'0'));
assert.equal(order.notificationId,reference);
assert.equal(order.inspectionId,first.id);
assert.equal(order.source,'notificacao_inspecao');
assert.equal(order.priority,2,'respeita prioridade revisada');
assert.equal(order.status,'fila');
assert.equal(order.assigned,null);
assert.equal(order.bay,null);
assert.equal(order.scheduleShift,null);
assert.equal(order.stage,0);
assert.equal(order.approvedScope.estimatedHH,4.5);
assert.equal(order.report,note.description);
assert.equal(order.options.length,6);
assert.ok(order.options.every(x=>x.length===4));
assert.equal(note.status,'convertida_os');
assert.equal(note.workOrderId,order.id);
assert.equal(I.summary(s).converted,1);
assert.ok(I.commitConversion(s,data,E,reference).error,'impede OS duplicada');
assert.ok(I.review(s,reference,'archive',{reason:'Desejo arquivar a ordem já criada.'}).error,'histórico de OS não editável');
assert.equal(s.jobs.length,originalCount+1);
assert.equal(E.validate(s),true,'save compatível com o motor');
assert.ok(P.compute(s,data).ranked.some(x=>x.id===order.id),'OS entra no planejamento PCM');
const another=inspections[1];assert.equal(I.inspect(s,data,another.id).status,'finding');
const other=I.notify(s,another.id,'Vazamento sensitivo com localização ainda não identificada.','baixa').notification;
assert.ok(I.review(s,other.id,'archive',{reason:'A avaliação didática não confirmou necessidade de intervenção.'}).ok);
assert.equal(other.status,'arquivada_pcm');
assert.ok(I.commitConversion(s,data,E,other.id).error,'arquivada não pode gerar OS');
assert.equal(other.workOrderId,null);
assert.ok(Array.isArray(note.reviewHistory)&&note.reviewHistory.length===4,'rastreabilidade de retorno, complementação, aprovação e conversão');
const v=V.render(s,data,I);
for(const token of ['MESA PCM','ESCOPO APROVADO','data-notification-action="approve"','data-notification-action="return"','data-notification-action="archive"','data-notification-action="resubmit"','data-notification-action="convert"']){
 if(token.startsWith('data-notification-action'))continue;
 assert.ok(v.includes(token),token);
}
const live=I.notify(s,another.id,'Duplicidade não deveria ser permitida','baixa');assert.ok(live.error);
const draft=JSON.parse(JSON.stringify(s));
I.normalized(draft);assert.deepEqual(draft,s,'save preservado após normalização');
const html=fs.readFileSync(path.join(__dirname,'../phaser-play/index.html'),'utf8');
const game=fs.readFileSync(path.join(__dirname,'../phaser-play/game.js'),'utf8');
assert.ok(game.includes('I.commitConversion(state,data,E,id)'),'criação manual conectada ao motor');
assert.ok(game.includes('I.review(state,id,decision,payload,data,E)'),'revisão conectada à UI');
assert.ok(html.includes('inspection.js?v=0.9.2'));
assert.ok(html.includes('inspection-view.js?v=0.9.8'));
assert.ok(html.includes('pcmScopeRow')&&html.includes('pcmActions'),'interface PCM responsiva');
const saveLegacy=E.create(data,()=>.5);
I.normalized(saveLegacy);assert.equal(I.summary(saveLegacy).approved,0,'compatível com saves anteriores');
const noteMarkup=JSON.parse(JSON.stringify(note));
noteMarkup.description='<script>alert("XSS")</script> falha reportada com texto perigoso';
noteMarkup.reportedIndication=noteMarkup.description;
const cloned=JSON.parse(JSON.stringify(s));cloned.notifications=[noteMarkup];
const unsafe=V.render(cloned,data,I);
assert.ok(!unsafe.includes('<script>')&&unsafe.includes('&lt;script&gt;'),'descrições sempre escapadas');
console.log('OK: PCM devolve/complementa/arquiva/aprova, OS explícita sem duplicação, histórico, saves e renderização segura.');
