/* P.O.R.C.A.R.I.A. — PCM, testes puros sem navegador. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const E=require(path.join(root,'engine.js'));
const P=require(path.join(root,'phaser-play','planning.js'));
const data=JSON.parse(fs.readFileSync(path.join(root,'game-data.json'),'utf8'));
const state=E.create(data,()=>0.42);
const initial=JSON.stringify(state);
let p=P.compute(state,data);
assert.equal(JSON.stringify(state),initial,'planejamento apenas lê o save');
assert.equal(p.freeBays.length,3,'boxes livres na abertura');
assert.equal(p.freeMechanics.length,3,'três titulares em campanha nova');
assert.equal(p.remainingStarts,3,'capacidade limitada pelo número de boxes');
assert.equal(p.remainingGrossHours,31.5,'HH úteis = 3 profissionais × 10,5h e 3 boxes');
assert.equal(p.ranked.length,3,'todas as OS iniciais entram na fila planejável');
assert.ok(p.ranked.every(j=>j.freeBays.length===3),'cada sugestão considera a ocupação presente');
assert.ok(p.ranked.every((j,i,arr)=>i===0||arr[i-1].score>=j.score),'fila ordenada por pontuação');
assert.ok(p.ranked.every(j=>j.score>=0&&j.ageHours===0),'índice explicável e sem idade negativa');
assert.equal(p.countCriticalWaiting,state.jobs.filter(j=>j.priority===3).length,'contagem de críticas sem equipe');
const j=state.jobs[0],sc=E.scenario(data,j.scene);
state.tools[sc.tool]=true;
state.team[0].role=sc.category;state.team[0].skill=88;state.team[0].mental=99;state.team[0].physical=99;
for(const m of state.team.slice(1)){m.role='outra';m.skill=55;m.mental=70;m.physical=70}
p=P.compute(state,data);
let row=p.ranked.find(x=>x.id===j.id);
assert.equal(row.readiness.kind,'ready','ferramental presente permite investigação');
assert.equal(row.recommended.mechanicId,state.team[0].id,'mecânico com especialidade relevante sugerido');
assert.equal(row.recommended.bay,0,'primeiro box livre sugerido');
assert.equal(row.recommended.roleMatch,true,'compatibilidade real da especialidade');
assert.equal(state.team[0].assigned,null,'consultar sugestão não aloca automaticamente');
assert.equal(E.attach(state,j.id,row.recommended.mechanicId,row.recommended.bay,true),null,'motor autoriza sugestão explícita');
p=P.compute(state,data);
assert.equal(p.remainingStarts,2,'capacidade decrementa após alocação');
assert.equal(p.remainingGrossHours,21,'HH úteis remanescentes decrementam');
assert.equal(p.ranked.length,2,'OS já alocada sai das sugestões');
assert.ok(p.ranked.every(x=>x.recommended?.bay!==0),'box ocupado nunca é recomendado');
assert.ok(p.ranked.every(x=>x.recommended?.mechanicId!==state.team[0].id),'mecânico ocupado não é recomendado');
const second=state.jobs.find(x=>!x.assigned);
const sc2=E.scenario(data,second.scene);
state.tools[sc2.tool]=false;
p=P.compute(state,data);
row=p.ranked.find(x=>x.id===second.id);
assert.equal(row.readiness.kind,'tool','ferramental é pré-condição de diagnóstico');
assert.equal(row.readiness.resource,sc2.tool);
assert.equal(row.recommended,null,'OS bloqueada não é alocada pelo atalho');
state.tools[sc2.tool]=true;
second.stage=6;second.materialUsed=false;state.stock[sc2.material]=0;
state.orders.push({id:'PC909',item:sc2.material,qty:1,eta:state.tick+1});
p=P.compute(state,data);
row=p.ranked.find(x=>x.id===second.id);
assert.equal(row.readiness.kind,'material','peça faltante bloqueia reparo mesmo se ETA próximo');
assert.equal(row.recommended,null,'pedido futuro não libera alocação');
assert.equal(row.inbound[0].turnsRemaining,1,'ETA exibido em turnos');
state.stock[sc2.material]=1;
p=P.compute(state,data);
row=p.ranked.find(x=>x.id===second.id);
assert.equal(row.readiness.kind,'ready','saldo real libera recomendação');
state.stock[sc2.material]=0;second.materialUsed=true;
p=P.compute(state,data);
assert.equal(p.ranked.find(x=>x.id===second.id).readiness.kind,'ready','material já baixado não é cobrado de novo');
second.materialUsed=false;second.stage=0;
state.team[1].restAt=state.tick;
p=P.compute(state,data);
assert.ok(!p.freeMechanics.some(x=>x.id===state.team[1].id),'descansando não recebe recomendação');
state.team[1].restAt=null;
state.team[1].mental=12;state.team[1].physical=18;
assert.equal(P.candidateScore(state.team[1],sc2).fatigued,true,'fadiga explicitada');
assert.equal(P.compute(state,data).remainingGrossHours,21,'fadiga reduz score, não remove mecanicamente da capacidade útil');
for(const x of state.jobs.filter(x=>!x.assigned))state.tools[E.scenario(data,x.scene).tool]=true;
for(const x of state.jobs.filter(x=>!x.assigned)){
 const row=P.compute(state,data).ranked.find(z=>z.id===x.id);
 // O bloqueio manual é permitido pelo motor; o planner oferece alocação automática apenas quando apto.
 if(row?.recommended)assert.equal(E.attach(state,x.id,row.recommended.mechanicId,row.recommended.bay,true),null);
}
p=P.compute(state,data);
assert.equal(p.remainingGrossHours,0,'sem boxes livres, nenhuma HH de oportunidade para novas alocações');
assert.ok(p.ranked.every(x=>x.recommended===null),'sem boxes livres, nenhuma sugestão executável');
const html=fs.readFileSync(path.join(root,'phaser-play','index.html'),'utf8');
const js=fs.readFileSync(path.join(root,'phaser-play','game.js'),'utf8');
assert.equal((html.match(/data-panel="planning"/g)||[]).length,1,'painel de planejamento único');
assert.ok(html.includes('planning.js?v=0.7.8'),'módulo de planejamento com cache de versão');
assert.ok(html.includes('game.js?v=0.8.26'),'jogo com cache de versão');
assert.ok(js.includes('function drawPlanning()'),'renderizador do painel presente');
assert.ok(js.includes('PORCARIA_PLANNING.compute(state,data)'),'planejamento deriva diretamente do estado do motor');
assert.ok(js.includes('data-plan-assign'),'sugestão exige ação explícita');
assert.ok(js.includes('dataset.planTick'),'recalcula sugestões a partir do turno');
assert.ok(js.includes('E.attach(state,planAssignment.dataset.planAssign'),'motor valida a alocação');
assert.ok(!js.includes('E.orderMaterial(state,data,planAssignment'),'planejador não compra automaticamente');
console.log('OK: priorização, equipe, HH brutas, faltas, ETAs, descanso, alocação explícita e UI do PCM.');
