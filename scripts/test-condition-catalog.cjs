/* Catálogo v1: recebimento de ocorrências sem estudos acionados manualmente. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const D=require('../game-data.json');
const E=require('../engine.js');
const I=require('../phaser-play/inspection.js');
const M=require('../phaser-play/monitoring.js');
const C=require('../phaser-play/condition-catalog.js');
const V=require('../phaser-play/inspection-view.js');
const S=require('../phaser-play/sector-views.js');
const cats=['oil','faults','undercarriage','fps','components'];
assert.equal(C.ENTRIES.length,120);
assert.deepEqual(cats.map(c=>C.byCategory(c).length),[24,24,24,24,24]);
assert.equal(new Set(C.ENTRIES.map(e=>e.id)).size,C.ENTRIES.length,'IDs imutáveis/únicos');
for(const e of C.ENTRIES){
 assert.ok(e.title.length>15&&e.baseline.length>40,e.id+' observação rastreável');
 assert.ok(D.models.some(m=>m.id===e.modelId),e.id+' frota existente');
 assert.ok(!e.escalationScenario||D.scenarios.some(s=>s.id===e.escalationScenario&&s.modelId===e.modelId),e.id+' roteiro compatível');
 assert.ok(e.followupTool===null||Object.hasOwn(D.tools,e.followupTool),e.id+' ferramental cadastrado');
 assert.ok(e.results.every(x=>['estavel','inconclusivo','agravamento'].includes(x)));
}
assert.ok(C.byCategory('fps').every(e=>e.escalationScenario===null),'FPS não recebe roteiro OEM inventado');
const s=E.create(D,()=>.5);I.normalized(s);
const baseJobs=s.jobs.length;
const inbound=[];
for(let tick=0;tick<=8;tick+=2){
 s.tick=tick;
 const received=M.receive(s,D,I,{initial:tick===0});
 assert.equal(received.received.length,1,'1 condição recebida por ciclo de entrada');
 const n=received.received[0];
 inbound.push(n);
 assert.equal(n.monitorOnly,true);
 assert.equal(n.sourceScenario,null,'sinal não é diagnóstico antecipado');
 assert.equal(n.inspectionId,null,'fonte não é inspeção inventada');
 assert.equal(n.status,'aguarda_revisao_pcm');
 assert.ok(n.monitorProtocol&&n.monitorCategory);
 assert.equal(M.receive(s,D,I).received.length,0,'não duplicar ao reabrir menu');
 assert.equal(s.jobs.length,baseJobs,'nenhuma OS criada por recepção');
}
assert.deepEqual(inbound.map(x=>x.monitorCategory),cats,'rodízio dos cinco domínios');
assert.equal(M.summary(s).total,5);
assert.ok(E.validate(JSON.parse(JSON.stringify(s))),'save serializável');
const oil=inbound[0],fault=inbound[1],fps=inbound[3];
assert.equal(M.decide(s,oil.id,'trend',2).ok,true);
assert.equal(M.decide(s,fault.id,'trend',2).ok,true);
assert.equal(M.decide(s,fps.id,'sample',2).ok,true);
s.tick=10;
s.tools.COLETA=false;
assert.equal(M.collect(s,oil.id).error!==undefined,true,'coleta de óleo exige instrumento');
s.tools.COLETA=true;
const before=s.cash;
assert.equal(M.collect(s,oil.id).ok,true);
assert.equal(s.cash,before-40,'custo de óleo não extrapolado');
const afterOil=s.cash;
s.tools.MULT=false;
assert.equal(M.collect(s,fault.id).error!==undefined,true,'leitura de falha precisa de instrumento');
s.tools.MULT=true;
assert.equal(M.collect(s,fault.id).ok,true);
assert.equal(s.cash,afterOil,'outra leitura não cobra coleta de óleo');
assert.equal(M.collect(s,fps.id).ok,true,'FPS não recebe instrumento inventado');
assert.equal(s.cash,afterOil);
const fpsRaised=M.escalate(s,D,I,fps.id);
assert.equal(fpsRaised.ok,true);
assert.equal(fpsRaised.escalation.sourceScenario,null);
assert.equal(fpsRaised.escalation.requiresScenarioMapping,true,'roteiro FPS pendente de curadoria');
assert.equal(s.jobs.length,baseJobs,'escalonamento não cria OS');
assert.equal(I.review(s,fpsRaised.escalation.id,'approve',{},D,E).error!==undefined,true,'PCM não aprova sem roteiro');
const screen=S.monitoring(s,D,M,V,I,E,'faults');
assert.ok(screen.includes('SINAIS RECEBIDOS'));
assert.ok(screen.includes('CATÁLOGO DE SINTOMAS'));
assert.ok(screen.includes('FLT001'));
assert.ok(!screen.includes('data-monitor-start'),'sem botões de estudo');
assert.ok(!screen.includes('OIL001'),'aba individual respeita domínio');
const overview=S.monitoring(s,D,M,V,I,E,'overview');
assert.ok(overview.includes('FPS001')&&overview.includes('CMP001'));
const practice=V.render(s,D,I,E,null,M);
assert.ok(!practice.includes('data-monitor-start'),'nenhum estudo legado na interface');
const html=fs.readFileSync('phaser-play/index.html','utf8');
const game=fs.readFileSync('phaser-play/game.js','utf8');
const sw=fs.readFileSync('sw.js','utf8');
assert.ok(html.indexOf('oil-catalog-expansion.js')<html.indexOf('condition-catalog.js')&&html.indexOf('condition-catalog.js')<html.indexOf('monitoring.js'),'expansão e catálogo carregados antes do monitoramento');
assert.ok(game.includes('M.receive(state,data,I,{initial:true})')&&game.includes('M.receive(state,data,I);'),'chegada ligada à campanha');
assert.ok(!game.includes("data-monitor-start"));
assert.ok(sw.includes("'./phaser-play/condition-catalog.js'"),'catálogo disponível offline');
console.log('OK: 120 sintomas, 5 fontes, rodízio, idempotência, custo/ferramenta, FPS sem gabarito e interface.');
