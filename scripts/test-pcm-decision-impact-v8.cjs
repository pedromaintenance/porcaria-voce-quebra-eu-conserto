/* PCM ciclo 8: compras, espera, tempo de OS e oportunidade virtual. */
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const D=require('../game-data.json'),E=require('../engine.js'),I=require('../phaser-play/inspection.js');
const P=require('../phaser-play/planning.js'),X=require('../phaser-play/decision-impact.js');
assert.equal(X.VERSION,'8.0.0');
assert.equal(D.scenarios.length,124);
assert.equal(D.items.FPTP.unit,520);
const item=D.items.FPTP;
const q=X.quote(item,2,5);
assert.equal(q.normal.cost,1040);
assert.equal(q.urgent.cost,1716);
assert.equal(q.premium,676);
assert.deepEqual([q.normal.turnsMin,q.normal.turnsMax,q.urgent.turnsMin,q.urgent.turnsMax],[4,5,1,2]);
assert.equal(q.normal.etaEarliest,9);
assert.equal(q.urgent.etaEarliest,6);
assert.equal(q.probabilityExtraTurn,.18);
assert.equal(X.quote(item,0),null,'não aceitar quantidade nula');
const fresh=()=>{const st=E.create(D,()=>.5);I.normalized(st);return st};
const s0=fresh(),before=JSON.stringify(s0);
assert.ok(Array.isArray(s0.purchaseHistory)&&s0.purchaseHistory.length===0);
const zero=X.compute(s0,D);
assert.equal(JSON.stringify(s0),before,'consulta de impacto não muda save');
assert.equal(zero.metrics.activeDowntimeHours,0);
assert.equal(zero.metrics.purchaseTotal,0);
assert.equal(zero.metrics.openPurchases,0);
assert.equal(zero.metrics.virtualOpportunityCost,0);
assert.equal(zero.metrics.indicativeInventoryValue>=0,true);
assert.ok(zero.warning.includes('NÃO descontos do caixa'));
function setup(){
 const s=fresh(),scenario=D.scenarios.find(x=>x.id==='INC101');
 s.jobs=[{...s.jobs[0],id:'OS9001',scene:scenario.id,modelId:scenario.modelId,asset:scenario.modelId+'·99',title:scenario.title,
  tickOpen:s.tick,priority:3,stage:6,status:'apto',assigned:null,bay:null,materialUsed:false,repairRemaining:1,
  exposureShifts:0,materialWaitShifts:0,toolWaitShifts:0,diagnosisQueueShifts:0}];
 s.stock[scenario.material]=0;s.tools[scenario.tool]=false;
 return {s,job:s.jobs[0],scenario};
}
const normal=setup(),fast=setup();
const pre=X.compute(normal.s,D),work=pre.active[0],parts=work.procurement;
assert.equal(parts.onHand,0);assert.equal(parts.demandDiagnosed,1);assert.equal(parts.shortfall,1);
assert.equal(parts.inbound.length,0);
assert.equal(P.compute(normal.s,D).ranked[0].readiness.kind,'tool');
assert.equal(E.orderMaterial(normal.s,D,'FPTP',1,false,()=>.5),null);
assert.equal(E.orderMaterial(fast.s,D,'FPTP',1,true,()=>.5),null);
assert.equal(normal.s.orders[0].eta,4);
assert.equal(fast.s.orders[0].eta,1);
assert.equal(normal.s.cash-fast.s.cash,338,'urgente cobra prêmio em caixa');
assert.equal(normal.s.purchaseHistory[0].demandAtPurchase,1);
assert.equal(fast.s.purchaseHistory[0].stockAtPurchase,0);
assert.equal(X.compute(normal.s,D).metrics.purchaseTotal,520);
assert.equal(X.compute(fast.s,D).metrics.purchaseTotal,858);
assert.equal(X.compute(normal.s,D).active[0].procurement.inbound[0].turnsRemaining,4);
assert.equal(X.compute(normal.s,D).active[0].procurement.shortfall,0,'pedido de compra cobre demanda mas não estoque');
assert.equal(X.compute(normal.s,D).active[0].procurement.couldReserveNow,false);
E.advance(normal.s,D,()=>.5);
E.advance(fast.s,D,()=>.5);
assert.equal(normal.s.orders.length,1,'compra normal não entrega no primeiro turno');
assert.equal(fast.s.orders.length,0,'urgência entrega no final do primeiro turno');
assert.equal(normal.s.stock.FPTP,0);
assert.equal(fast.s.stock.FPTP,1);
assert.equal(fast.s.purchaseHistory[0].receivedTick,1);
assert.equal(normal.job.exposureShifts,1);
assert.equal(normal.job.materialWaitShifts,1);
assert.equal(normal.job.toolWaitShifts,1);
assert.equal(normal.job.diagnosisQueueShifts,0);
assert.equal(X.compute(normal.s,D).metrics.activeDowntimeHours,12);
assert.equal(X.compute(normal.s,D).metrics.materialWaitShifts,1);
assert.equal(X.compute(normal.s,D).metrics.toolWaitShifts,1);
assert.equal(X.compute(normal.s,D).metrics.virtualOpportunityCost,1800,'12h × 150 R$/h virtuais em prioridade 3');
assert.equal(X.compute(fast.s,D).active[0].procurement.couldReserveNow,true,'pedido entregue não executa reparo');
assert.equal(P.compute(fast.s,D).ranked[0].readiness.kind,'tool','ferramenta ainda limita');
assert.equal(E.buyTool(fast.s,D,'METR'),null);
assert.equal(P.compute(fast.s,D).ranked[0].readiness.kind,'ready');
const other=setup();const cash=other.s.cash;
assert.equal(E.orderMaterial(other.s,D,'FPRT',1,false,()=>.5),null);
assert.equal(other.s.cash,cash-D.items.FPRT.unit);
assert.equal(other.s.purchaseHistory[0].demandAtPurchase,0,'material não associado a demanda diagnosticada');
assert.equal(X.compute(other.s,D).active[0].procurement.shortfall,1,'comprar item distinto não resolve falta');
other.job.plannerDiagnosis={errorCount:2,evaluated:true};
other.job.reworkHours=1.5;
assert.equal(X.compute(other.s,D).metrics.evaluatedPlannerErrors,2);
assert.equal(X.compute(other.s,D).metrics.reworkHours,1.5);
