/* Regressão sessão 8 — diagnóstico por evidências na mesa PCM. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const D=require('../game-data.json'),E=require('../engine.js');
const I=require('../phaser-play/inspection.js');
const T=require('../phaser-play/evidence.js');
const V=require('../phaser-play/inspection-view.js');
assert.equal(D.scenarios.length,124);
assert.equal(D.paths.length,493);
const ids=['INC066','INC067','INC076','INC077','INC086','INC087'];
const cases=ids.map(id=>D.scenarios.find(c=>c.id===id));
for(const [i,c] of cases.entries()){
 assert.ok(c,ids[i]);
 assert.equal(c.diagnosticTests.length,3);
 assert.equal(new Set(c.diagnosticTests.map(t=>t.id)).size,3);
 for(const t of c.diagnosticTests){
  assert.equal(t.simulationOnly,true);
  assert.ok(D.tools[t.tool],t.id+' ferramenta existente');
  assert.ok(Number.isSafeInteger(t.cashCost)&&t.cashCost>0);
  assert.ok(t.label.length>20&&t.result.length>50&&t.limits.length>45);
  assert.ok(['observado','nao_observado','inconclusivo','convergente','divergente'].includes(t.outcome));
 }
}
for(const [a,b] of [[0,1],[2,3],[4,5]]){
 assert.deepEqual(cases[a].diagnosticTests.map(t=>t.id),cases[b].diagnosticTests.map(t=>t.id),'mesmos testes da hipótese diferencial');
 assert.ok(cases[a].diagnosticTests.some((x,i)=>x.result!==cases[b].diagnosticTests[i].result),'pelo menos um teste diferencia o mecanismo');
}
function fresh(){const s=E.create(D,()=>.5);I.normalized(s);return s;}
const s=fresh(),initialJobs=s.jobs.length,initialAssets=s.jobs.map(j=>j.asset);
let r=T.practice(s,D,I,'fuel');
assert.equal(r.ok,true);
const n=r.notification;
assert.equal(n.sourceScenario,'INC066');
assert.equal(n.status,'aguarda_revisao_pcm');
assert.equal(n.workOrderId,null);
assert.equal(n.practiceFamily,'fuel');
assert.equal(s.jobs.length,initialJobs,'nenhuma OS é criada pela bancada');
assert.deepEqual(s.jobs.map(x=>x.asset),initialAssets);
assert.equal(n.evidenceTests.length,0);
assert.equal(T.available(s,D,n.id).length,3);
assert.ok(T.available(s,D,n.id).every(x=>!x.completed));
const viewBefore=V.render(s,D,I,E,T);
assert.ok(viewBefore.includes('data-evidence-practice="fuel"'));
assert.ok(viewBefore.includes('data-evidence-test="press"'));
assert.ok(!viewBefore.includes(cases[0].diagnosticTests[0].result),'resultado só aparece após teste');
const cash=s.cash;
r=T.run(s,D,I,n.id,'press');
assert.equal(r.ok,true);
assert.equal(r.evidence.outcome,'convergente');
assert.equal(s.cash,cash-35);
assert.equal(n.evidenceTests.length,1);
assert.equal(r.evidence.source,'resultado_ficticio_sem_medicao_OEM');
assert.ok(T.available(s,D,n.id).find(x=>x.id==='press').completed);
const saved=JSON.parse(JSON.stringify(s));
assert.equal(E.validate(saved),true,'salvamento legado compatível');
assert.equal(saved.notifications[0].evidenceTests[0].result,r.evidence.result,'evidência persiste');
assert.ok(V.render(s,D,I,E,T).includes(r.evidence.result));
const duplicate=T.run(s,D,I,n.id,'press');
assert.ok(duplicate.error,'não repetir teste');
assert.equal(s.cash,cash-35);
const missing=T.run(s,D,I,n.id,'restrict');
assert.ok(missing.error.includes('Ferramenta'),'ferramenta inicialmente ausente');
assert.equal(n.evidenceTests.length,1);
s.tools.PDIF=true;
assert.equal(T.run(s,D,I,n.id,'restrict').ok,true);
assert.equal(T.run(s,D,I,n.id,'sample').ok,true);
assert.equal(n.evidenceTests.length,3);
assert.equal(T.run(s,D,I,n.id,'fake').error!==undefined,true,'não autorizar teste inexistente');
assert.equal(n.evidenceTests.length,3);
const second=T.practice(s,D,I,'fuel');
assert.equal(second.ok,true);
assert.equal(second.notification.sourceScenario,'INC067','variante troca sem expor sua causa no seletor');
assert.notEqual(second.notification.asset,n.asset,'frota sem duplicidade no turno');
assert.ok(T.practice(s,D,I,'fuel').error,'máximo dois casos por turno');
const options=I.hypotheses(s,D,E,n.id);
const sc=cases[0],truth=[...sc.path,sc.component,sc.damage,sc.cause];
assert.ok(options.every((xs,i)=>xs.length===4&&xs.some(x=>x.id===truth[i])));
const approved=I.review(s,n.id,'approve',{diagnosis:truth,action:'diagnosticar',trade:'mecanica',estimatedHH:4},D,E);
assert.equal(approved.ok,true,'verificações não impedem aprovação normal');
assert.equal(T.run(s,D,I,n.id,'press').error!==undefined,true,'bloqueio pós aprovação');
assert.equal(n.workOrderId,null);
const converted=I.commitConversion(s,D,E,n.id);
assert.equal(converted.ok,true);
assert.equal(converted.order.source,'notificacao_inspecao');
assert.equal(converted.order.plannerDiagnosis.evaluated,false);
assert.equal(n.evidenceTests.length,3,'evidências permanecem na notificação');
assert.equal(s.jobs.length,initialJobs+1);
const other=fresh();
const air=T.practice(other,D,I,'air');
assert.equal(air.ok,true);
assert.equal(air.notification.sourceScenario,'INC076');
assert.equal(T.run(other,D,I,air.notification.id,'airtight').error!==undefined,true,'ar comprimido exige ferramenta');
other.tools.PNEU=true;
assert.equal(T.run(other,D,I,air.notification.id,'airtight').ok,true);
const final=fresh();
const wheel=T.practice(final,D,I,'final');
assert.equal(wheel.ok,true);
assert.equal(wheel.notification.sourceScenario,'INC086');
assert.equal(T.run(final,D,I,wheel.notification.id,'oil').ok,true);
assert.equal(wheel.notification.evidenceTests[0].outcome,'inconclusivo','partículas não identificam rolamento/engrenagem');
const old=fresh();
assert.ok(V.render(old,D,I,E).includes('INSPEÇÃO'),'renderização anterior permanece compatível');
assert.equal(T.practice(old,D,I,'unknown').error!==undefined,true);
const game=fs.readFileSync(path.join(__dirname,'../phaser-play/game.js'),'utf8');
assert.ok(game.includes('T.practice(state,data,I,')&&game.includes('T.run(state,data,I,'));
const html=fs.readFileSync(path.join(__dirname,'../phaser-play/index.html'),'utf8');
assert.ok(html.includes('evidence.js?v=0.9.3'));
console.log('OK sessão 8: seis variantes, três testes, custo, ferramenta, persistência, PCM e sem resposta antecipada.');
