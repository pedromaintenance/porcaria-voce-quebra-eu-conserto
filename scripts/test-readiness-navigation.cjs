/* P.O.R.C.A.R.I.A. v0.8.8 — regressão de contexto da OS e alertas consultivos. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'..');
const E=require(path.join(root,'engine.js'));
const R=require(path.join(root,'phaser-play','readiness.js'));
const data=JSON.parse(fs.readFileSync(path.join(root,'game-data.json'),'utf8'));
const state=E.create(data,()=>0.42);
const j=state.jobs[0],s=E.scenario(data,j.scene),m=state.team[0];
assert.equal(E.attach(state,j.id,m.id,0,true),null);
state.tools[s.tool]=false;
let report=R.compute(state,data);
let issue=report.warnings.find(w=>w.id==='box-0');
assert.ok(issue,'ferramenta bloqueada gera alerta');
assert.equal(issue.action.kind,'store');
assert.equal(issue.action.item,s.tool);
assert.equal(issue.action.jobId,j.id,'retorno carrega a OS de origem');
state.tools[s.tool]=true;
j.stage=6;j.materialUsed=false;state.stock[s.material]=0;
report=R.compute(state,data);
issue=report.warnings.find(w=>w.id==='box-0');
assert.equal(issue.action.item,s.material);
assert.equal(issue.action.jobId,j.id);
assert.equal(report.bays[0].kind,'material');
const js=fs.readFileSync(path.join(root,'phaser-play','game.js'),'utf8');
const html=fs.readFileSync(path.join(root,'phaser-play','index.html'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
assert.ok(js.includes("function focusStore(item,fromJob)"),'atalho preserva OS de origem');
assert.ok(js.includes('stockReturnJobId=source?.id||null'),'somente OS existente vira contexto');
assert.ok(js.includes('data-stock-return'),'retorno renderizado no estoque');
assert.ok(js.includes("if(!origin){stockReturnJobId=null;drawStore();notify("),'retorno obsoleto é tratado');
assert.ok(js.includes("stockReturnJobId=null;pick(origin.id,orderReturnPanel)"),'retorno abre OS original e preserva o contexto');
assert.ok(js.includes("j.stage<6?'🔎 Material a confirmar no diagnóstico'"),'detalhe não revela peça não confirmada');
assert.ok(js.includes("j.stage>=6?'<button class="),'peça confirmada é consultável');
assert.ok(js.includes("data-do=\"stockTool\""),'ferramenta consultável');
assert.ok(js.includes("data-do=\"stockPart\""),'peça consultável');
assert.ok(js.includes("data-return-job="),'alertas e briefing propagam origem');
assert.ok(js.includes("data-readiness-expand"),'alertas adicionais possuem controle');
assert.ok(js.includes("ready.warnings.slice(6).map(renderReadyAlert)"),'nenhum alerta descartado');
assert.ok(js.includes("extra.hidden=!extra.hidden"),'controle expansível não muda o motor');
assert.ok(html.includes('#readinessMore[hidden]{display:none!important}'),'alertas ocultos não vazam pelo CSS');
assert.ok(html.includes('aria-controls="readinessMore"')===false,'controle é gerado pelo JS');
assert.ok(html.includes('readiness.js?v=0.8.8')&&html.includes('game.js?v=0.9.4'),'cache atualizado');
assert.ok(sw.includes('porcaria-vqec-20261019-v111'));
assert.ok(sw.includes("'./phaser-play/readiness.js'"),'módulo consultivo entra no cache PWA');
console.log('OK: OS↔estoque, peça após diagnóstico, seis+ alertas acessíveis, cache atualizado.');
