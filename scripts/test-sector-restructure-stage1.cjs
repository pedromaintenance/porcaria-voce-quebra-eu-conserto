/* PORCARIA: regressão etapa 1 da reestruturação setorial. */
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const D=require('../game-data.json'),E=require('../engine.js'),I=require('../phaser-play/inspection.js');
const V=require('../phaser-play/inspection-view.js'),M=require('../phaser-play/monitoring.js'),S=require('../phaser-play/sector-views.js');
assert.equal(D.scenarios.length,100,'100 missões preservadas');
assert.equal(D.paths.length,387,'387 locais preservados');
assert.deepEqual(Object.keys(S.CATEGORIES),['overview','oil','faults','undercarriage','fps','components']);
const file=path.join(__dirname,'../phaser-play/assets/pedro-sala-controle.webp');
const image=fs.readFileSync(file);
assert.ok(image.length>100000,'asset original em alta resolução disponível');
assert.equal(image.toString('ascii',0,4),'RIFF','imagem WebP binária');
assert.equal(image.toString('ascii',8,12),'WEBP');
const save=E.create(D,()=>.4);I.normalized(save);
const prev=save.jobs.length;
assert.equal(save.inspections.length,0,'abrir inspeções não gera ronda automática');
const full=S.inspections(save,D,I,E);
assert.ok(full.includes('id="fieldAsset"')&&full.includes('id="fieldInspector"'));
assert.ok(full.includes('data-inspection-action="schedule"'));
assert.ok(!full.includes('data-evidence-practice')&&!full.includes('data-monitor-start'));
const staff=save.team.find(m=>!m.assigned&&m.restAt!==save.tick&&!E.TRAINING.active(save,m));
assert.ok(staff,'inspetor disponível');
const fleet=D.models.map(m=>Array.from({length:6},(_,k)=>m.id+'·'+String(k+1).padStart(2,'0'))
 .find(asset=>!save.jobs.some(j=>j.asset===asset))).filter(Boolean);
assert.ok(fleet.length>=9);
for(let i=0;i<7;i++){
 const s=I.schedule(save,D,fleet[i],staff.id);
 assert.equal(s.ok,true,'inspeção '+(i+1));
 assert.equal(s.inspection.inspectorId,staff.id);
 assert.equal(s.inspection.estimatedHH,1.5);
 assert.equal(s.inspection.asset,fleet[i]);
}
assert.equal(save.inspections.length,7,'inspeções não limitadas a três');
assert.equal(save.inspectionLabor.byEmployee[staff.id],10.5,'reservadas 10,5 HH');
assert.ok(I.schedule(save,D,fleet[7],staff.id).error.includes('Capacidade'),'oitava excede turno');
assert.ok(I.schedule(save,D,fleet[0],staff.id).error,'ativo não repetido');
const caught=save.inspections[0];
const opened=I.inspectAndRoute(save,D,caught.id);
assert.ok(opened.ok);
if(opened.status==='finding'){
 assert.ok(opened.notification,'enviar achado automaticamente ao PCM');
 assert.equal(opened.notification.status,'aguarda_revisao_pcm');
 assert.equal(opened.notification.workOrderId,null,'sem OS na inspeção');
}
const after=S.inspections(save,D,I,E);
assert.ok(after.includes('INSPEÇÃO DE CAMPO'));
assert.equal(save.jobs.length,prev,'inspeção não inicia reparo');
const monitor=M.open(save,D,I,'baseline');
assert.equal(monitor.ok,true);
const planning=S.planning(save,D,I,E,V);
assert.ok(planning.includes('CARTEIRA DE NOTIFICAÇÕES'));
assert.ok(planning.includes('PRÉ-DIAGNÓSTICO'));
assert.ok(!planning.includes('data-monitor-action'),'monitoramento não aparece no planejamento');
assert.ok(!planning.includes('data-evidence-test'),'testes não são realizados pelo PCM');
const monitorView=S.monitoring(save,D,M,V,I,E,'oil');
assert.ok(monitorView.includes('pedro-sala-controle.webp'));
assert.ok(monitorView.includes('class="controlRoomSidebar"'),'menu único cobre os botões do asset');
assert.ok(monitorView.includes('aria-label="Menu da sala de controle"'),'navegação desktop acessível');
assert.ok(monitorView.includes('aria-label="Menu de monitoramento no celular"'),'fallback acessível');
assert.equal((monitorView.match(/class="controlNavItem(?: is-current)?"/g)||[]).length,6,'seis categorias com botões sólidos');
assert.equal((monitorView.match(/class="controlMobileNavItem(?: is-current)?"/g)||[]).length,6,'seis opções mobile');
assert.equal((monitorView.match(/aria-pressed="true"/g)||[]).length,2,'seleção espelhada nos dois menus');
assert.ok(!monitorView.includes('controlHotspot'),'markup de hotspots removido');
assert.ok(monitorView.includes('data-monitor-category="faults"'));
assert.ok(monitorView.includes('data-monitor-category="undercarriage"'));
assert.ok(monitorView.includes('data-monitor-category="fps"'));
assert.ok(monitorView.includes('data-monitor-category="components"'));
assert.ok(monitorView.includes('SINAIS RECEBIDOS'));
assert.ok(monitorView.includes('CATÁLOGO DE SINTOMAS'));
assert.ok(!monitorView.includes('data-monitor-start'),'sem botões de estudos antigos');
const fView=S.monitoring(save,D,M,V,I,E,'faults');
assert.ok(fView.includes('CATÁLOGO DE SINTOMAS')&&fView.includes('Códigos de falha'));
const fpsView=S.monitoring(save,D,M,V,I,E,'fps');
assert.ok(fpsView.includes('FPS')&&!fpsView.includes('CARTEIRA DE ANÁLISES DE ÓLEO'));
assert.ok(S.monitoring(save,D,M,V,I,E,'not-an-option').includes('Visão geral'));
const oldSave=JSON.parse(JSON.stringify(save));
assert.equal(E.validate(oldSave),true,'partidas persistem no formato anterior');
const game=fs.readFileSync(path.join(__dirname,'../phaser-play/game.js'),'utf8');
assert.ok(game.includes("data-open-panel=\"monitoring\"")||game.includes("name==='monitoring'"));
assert.ok(game.includes('S.inspections(state,data,I,E)'));
assert.ok(game.includes('S.planning(state,data,I,E,IV)'));
assert.ok(game.includes('S.monitoring(state,data,M,IV,I,E,monitorCategory)'));
assert.ok(!game.includes('I.plan(state,data);save();drawInspection()'),'sem ronda automática');
const html=fs.readFileSync(path.join(__dirname,'../phaser-play/index.html'),'utf8');
assert.ok(html.includes('sector-views.js?v=0.9.6'));
assert.ok(html.includes('.controlRoomSidebar{')&&html.includes('background:#081b2c'),'painel opaco substitui hotspots transparentes');
assert.ok(html.includes('.controlNavItem{')&&html.includes('.controlRoomMobileMenu{'),'menu de botões sólidos e fallback mobile');
assert.ok(!html.includes('.controlHotspot'),'posicionamento individual antigo removido');
assert.ok(html.includes('@media(max-width:690px)'),'layout mobile não cobre a arte com botões minúsculos');
assert.ok(html.includes('data-open-panel="planning"'));
assert.ok(html.includes('data-open-panel="monitoring"'));
console.log('OK: menu Pedro, 6 setores monitoráveis, Planejamento isolado, inspeção livre por HH e saves.');
