/* Ciclo 27: composição responsiva da Fila de OS, Monitoramento e Planejamento. */
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('phaser-play/index.html');
const css=read('phaser-play/responsive-scenes-v27.css');
const js=read('phaser-play/game.js');
const guide=read('phaser-play/mobile-panel-guide.js');
const sw=read('sw.js');
const queue=html.match(/<section class="panel" data-panel="queue">([\s\S]*?)<section class="panel" data-panel="inspection">/)?.[1];
assert.ok(queue,'Fila de OS continua existente');
assert.ok(queue.includes('class="radioDispatchArt"') && queue.includes('id="radioQueueSpotlight"'));
assert.ok(queue.includes('./assets/elton-sala-radio.webp'));
assert.ok(queue.indexOf('id="radioQueueSpotlight"')<queue.indexOf('id="queueSearch"'));
assert.ok(queue.indexOf('id="queueSearch"')<queue.indexOf('id="queue"'));
assert.ok(html.includes('class="scene-tools" hidden aria-hidden="true"'),'Visual inacessível em desktop e mobile');
assert.ok(css.includes('.scene-tools{display:none!important}'));
assert.ok(css.includes('html.mobile-play .bayHUD{display:none!important}'),'HUD dos boxes oculto só no celular');
assert.ok(!css.includes('html:not(.mobile-play) .bayHUD{display:none'));
assert.ok(html.includes('responsive-scenes-v27.css?v='),'CSS aplicado após estilos existentes');
assert.ok(sw.includes('./phaser-play/responsive-scenes-v27.css'));
assert.ok(sw.includes('scenes0929'),'cache renovado');
assert.ok(guide.includes("{label:'Categorias',selector:'.controlRoomSidebar'}"),'atalho aponta para sidebar real');
assert.ok(js.includes("visibleJobs.slice(0,3)"),'apenas três primeiras OS no preview');
assert.ok(js.includes("const visibleJobs=[...state.jobs].filter"),'lista e preview recebem mesmo filtro');
assert.ok(js.includes("$('queue').innerHTML=visibleJobs.map"),'lista completa continua abaixo');
assert.ok(js.includes("data-pick=\"'+esc(j.id)+'\""),'prévia abre a OS original');
assert.ok(js.includes("FILTER.queue==='critical'")&&js.includes('FILTER.query.toLowerCase()'));
assert.ok(css.includes('.radioQueueSpotlight{position:absolute'),'card sobreposto à ilustração');
assert.ok(css.includes('left:57%;right:1.5%'),'reserva mais da metade esquerda para Elton e mão');
assert.ok(css.includes('grid-template-rows:repeat(3,minmax(0,1fr))'),'três cartões em coluna sem deslocar a ilustração');
assert.ok(css.includes('.radioDispatchArt>img{display:block;width:100%;height:100%;object-fit:contain'),'Elton sempre completo');
assert.ok(css.includes('.controlRoomStage>img{width:100%;height:100%;object-fit:contain'),'Pedro não é cortado');
assert.ok(css.includes('html.mobile-play .controlRoomSidebar{display:flex!important'),'menu desktop reaproveitado no celular');
assert.ok(css.includes('html.mobile-play .controlRoomMobileMenu{display:none!important'),'não duplicar menu fora da foto');
// Área segura para o rosto de Pedro: sidebar ocupa x <= 33%; Elton: preview x >= 55%.
const sidebar=css.match(/\.controlRoomSidebar\{display:flex!important;left:([0-9.]+)%;top:[^}]+?max-width:([0-9.]+)%/);
assert.ok(sidebar,'limite de nav Pedro declarado');
assert.ok(Number(sidebar[1])+Number(sidebar[2])<=35,'menu não cobre a metade do rosto de Pedro');
assert.ok(css.includes('overflow-y:auto'),'menu de Pedro pode rolar dentro do próprio painel');
assert.ok(css.includes('.planningRoomStage,html.mobile-play .planningRoomStage{display:block;width:min(100%,60dvh,560px)'),'planejamento respeita altura do viewport em desktop e celular');
assert.ok(css.includes('object-fit:contain!important;object-position:center!important'),'planejamento não corta a arte');
assert.ok(css.includes('@media(max-height:520px)'),'ajuste de telas paisagem curtas');
// Integridade: sem mudar o catálogo de seis níveis ou os dados técnicos.
const D=JSON.parse(read('game-data.json'));
assert.equal(D.catalog.parts.length,683);
assert.equal(D.scenarios.length,124);
console.log('OK Ciclo 27: Elton + 3 OS, Pedro com menu à esquerda, artes inteiras, Visual removido e HUD mobile oculto.');
