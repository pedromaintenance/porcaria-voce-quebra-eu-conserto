/* P.O.R.C.A.R.I.A. 0.8.9 — importação de sprite CAT 777E somente local. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const g=fs.readFileSync(path.join(root,'phaser-play/game.js'),'utf8');
const html=fs.readFileSync(path.join(root,'phaser-play/index.html'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
const map=JSON.parse(fs.readFileSync(path.join(root,'phaser-play/scene-map.json'),'utf8'));
assert.ok(g.includes("truck:'./assets/equipment/cat777e_v3.webp'"),'asset original mantido');
assert.ok(g.includes("CUSTOM_TRUCK_KEY='porcaria.phaser.customTruck.20261017.v0810'"),'chave não colide com save');
assert.ok(g.includes("sceneStore('save',file,'truckSprite')"),'importação persistida localmente');
assert.ok(g.includes("sceneStore('read',null,'truckSprite')"),'persistência reaberta no boot');
assert.ok(g.includes("sceneStore('delete',null,'truckSprite')"),'reversão remove conteúdo local');
assert.ok(g.includes("if(scene.textures.exists('truckCustom'))")||g.includes("scene.textures.exists(key)"),'textura substituível');
assert.ok(g.includes("trim_truckCustom"),'trim antigo invalidado ao substituir sprite');
assert.ok(g.includes("scene.textures.addImage('truckCustom',img)"),'imagem local vira textura Phaser');
assert.ok(g.includes("modelId==='EQ01'&&this.textures.exists('truckCustom')?'truckCustom':normalKey"),'override restrito ao 777E');
assert.ok(g.includes('scene.refresh();'),'render do box atualizado');
assert.ok(g.includes("['image/png','image/webp'].includes(file.type)"),'importação limitada a PNG/WebP');
assert.ok(g.includes('file.size>5_000_000'),'restrição de arquivo');
assert.ok(g.includes('w<100||h<100||w>4096||h>4096'),'valida dimensão da imagem');
assert.ok(g.includes("restoreTruckSprite();notify("),'restaura versão sem modificar save');
assert.ok(!g.includes("state.truckSprite"),'asset não é incorporado ao estado da campanha');
assert.ok(html.includes('id="truckPicker"')&&html.includes('id="truckPickBtn"'));
assert.ok(html.includes('id="truckReset"')&&html.includes('id="truckAssetState"'));
assert.ok(html.includes('id="truckAssetThumb"'));
assert.ok(html.includes('game.js?v=0.8.30'));
assert.ok(html.includes('.scene-menu{max-height:min(78vh,630px)'),'menu de preview rolável');
assert.ok(sw.includes('porcaria-vqec-20261019-v109'));
assert.equal(map.bays.length,3);
assert.ok(html.includes('Não altera o save nem publica a imagem.'));
console.log('OK: override 777E opt-in, persistência local, fallback original e interface de revisão sem mudanças no save.');
