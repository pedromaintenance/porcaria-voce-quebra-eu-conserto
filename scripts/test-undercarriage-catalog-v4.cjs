/* Rodante ciclo 4: CTS, pneus, triagem e postergação sem limites OEM inventados. */
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const D=require('../game-data.json'),E=require('../engine.js'),I=require('../phaser-play/inspection.js');
const C=require('../phaser-play/condition-catalog.js'),M=require('../phaser-play/monitoring.js');
const S=require('../phaser-play/sector-views.js'),V=require('../phaser-play/inspection-view.js');
const U=require('../phaser-play/undercarriage-catalog-expansion.js');
const cats=['oil','faults','undercarriage','fps','components'];
assert.equal(U.VERSION,'4.0.0');assert.equal(C.VERSION,'6.0.0');
assert.equal(U.ENTRIES.length,18);
assert.equal(C.ENTRIES.length,120);
assert.deepEqual(cats.map(k=>C.byCategory(k).length),[24,24,24,24,24]);
assert.equal(new Set(C.ENTRIES.map(x=>x.id)).size,120,'sem ids duplicados');
for(let k=1;k<=24;k++){
 const id='UND'+String(k).padStart(3,'0'),e=C.get(id);
 assert.ok(e&&e.category==='undercarriage',id+' cadastrado');
 assert.ok(e.componentGroup&&e.assetZone&&e.verification&&e.uncertainty,id+' dossiê');
 assert.ok(['cts','termica','temperatura','inspecao_esteira','pneu','inspecao_pneu','pressao_pneu'].includes(e.measurementMethod),id+' método');
 assert.ok(e.measurementValue===null&&e.wearPercent===null&&e.referenceLimit===null&&e.unit===null,id+' sem leitura inventada');
 assert.equal(e.measurementStatus,'pendente');
 assert.ok(e.sourceKeys.every(key=>/^https:\/\//.test(C.SOURCES[key])),id+' fontes aplicáveis');
 assert.ok(['moderado','alto'].includes(e.delayRisk)&&e.riskOnDelay.length>20);
 if(e.delayThresholdTurns!==null){assert.equal(e.delayRisk,'alto');assert.equal(e.delayThresholdTurns,4);}
 assert.ok(!e.escalationScenario||D.scenarios.some(s=>s.id===e.escalationScenario&&s.modelId===e.modelId),id+' FMEA coerente');
 assert.ok(Object.hasOwn(D.tools,e.followupTool),id+' ferramenta real do jogo');
 assert.ok(e.results.every(x=>['estavel','inconclusivo','agravamento'].includes(x)));
 if(['pneu','inspecao_pneu','pressao_pneu'].includes(e.measurementMethod))assert.equal(e.followupTool,'CALP','pneu não usa CTS');
 if(e.measurementMethod==='cts')assert.equal(e.followupTool,'CTSM','CTS apenas para esteiras');
}
for(const id of ['UND007','UND008','UND009','UND012','UND016','UND019','UND020','UND021','UND024'])
 assert.equal(C.get(id).escalationScenario,null,'ausência de roteiro não vira OS: '+id);
for(const id of ['UND011','UND013','UND016','UND018','UND021'])
 assert.equal(C.get(id).triage,'avaliacao_prioritaria');
assert.ok(C.get('UND017').oemSpecificPending,'método Sandvik não é tabela CTS Cat');
const fresh=()=>{const s=E.create(D,()=>.5);I.normalized(s);return s;};
function receive(id){
 const s=fresh();s.monitoringFeedCursor=2;
 s.monitoringFeedSeen=C.byCategory('undercarriage').filter(p=>p.id!==id).map(p=>p.id);
 const got=M.receive(s,D,I,{initial:true});
 assert.equal(got.received.length,1,id+' recebimento');
 const n=got.received[0];assert.equal(n.monitorProtocol,id);
 assert.equal(n.monitorCategory,'undercarriage');
 assert.equal(n.sourceScenario,null);assert.equal(n.inspectionId,null);
 assert.equal(n.workOrderId,null);
 return {s,n};
}
const urgent=receive('UND021');
assert.equal(urgent.n.priority,'alta');
const card=V.monitorWidget(urgent.n,urgent.s,M);
assert.ok(card.includes('Inspeção de pneu — não CTS'));
assert.ok(card.includes('AVALIAÇÃO PRIORITÁRIA'));
assert.ok(card.includes('Medida / % desgaste / limite:'));
assert.ok(!card.includes('data-monitor-action="decide"'));
assert.ok(M.decide(urgent.s,urgent.n.id,'trend',2).error);
const beforeUrgent=urgent.s.jobs.length;
const e=M.escalate(urgent.s,D,I,urgent.n.id);
assert.equal(e.ok,true);
assert.equal(e.escalation.requiresScenarioMapping,true);
assert.equal(e.escalation.sourceScenario,null);
assert.equal(urgent.s.jobs.length,beforeUrgent);
assert.ok(I.review(urgent.s,e.escalation.id,'approve',{},D,E).error,'bloqueio OS sem FMEA');
const mapped=receive('UND013');
const esc=M.escalate(mapped.s,D,I,mapped.n.id);
assert.equal(esc.ok,true);
assert.equal(esc.escalation.sourceScenario,'INC011');
const late=receive('UND015');
assert.equal(M.decide(late.s,late.n.id,'trend',2).ok,true);
late.s.tick+=6;late.s.tools.CTSM=true;
const lateRead=M.collect(late.s,late.n.id);
assert.equal(lateRead.ok,true);
assert.equal(lateRead.sample.lateTurns,4);
assert.equal(lateRead.sample.delayEscalation,true);
assert.equal(lateRead.sample.trend,'agravamento','atraso de quatro turnos provoca agravamento virtual');
assert.equal(late.n.monitoring.status,'requer_avaliacao');
assert.ok(V.monitorWidget(late.n,late.s,M).includes('AGRAVAMENTO POR POSTERGAÇÃO SIMULADA'));
assert.ok(M.continueWatch(late.s,late.n.id,2).error,'não postergar uma condição já agravada');
assert.equal(M.escalate(late.s,D,I,late.n.id).ok,true);
const ontime=receive('UND015');
assert.equal(M.decide(ontime.s,ontime.n.id,'trend',2).ok,true);
ontime.s.tick+=2;ontime.s.tools.CTSM=true;
const normal=M.collect(ontime.s,ontime.n.id);
assert.equal(normal.sample.trend,'inconclusivo');
assert.equal(normal.sample.delayEscalation,false);
const tire=receive('UND024');
assert.equal(M.decide(tire.s,tire.n.id,'sample',2).ok,true);
tire.s.tick+=2;tire.s.tools.CALP=false;
assert.ok(M.collect(tire.s,tire.n.id).error,'exige instrumento pneu');
tire.s.tools.CALP=true;assert.equal(M.collect(tire.s,tire.n.id).ok,true);
const screen=S.monitoring(fresh(),D,M,V,I,E,'undercarriage');
assert.ok(screen.includes('24 ENTRADAS')&&screen.includes('UND024'));
assert.ok(screen.includes('CTS (leitura pendente)')&&screen.includes('Pneus (não CTS)'));
assert.ok(!screen.includes('OIL024'),'domínios separados');
const overall=S.monitoring(fresh(),D,M,V,I,E,'overview');
assert.ok(overall.includes('FLT024')&&overall.includes('UND024')&&overall.includes('OIL024'));
const html=fs.readFileSync('phaser-play/index.html','utf8');
const sw=fs.readFileSync('sw.js','utf8');
assert.ok(html.indexOf('undercarriage-catalog-expansion.js')<html.indexOf('condition-catalog.js'));
assert.ok(html.includes('monitoring.js?v=0.9.8'));
assert.ok(sw.includes("'./phaser-play/undercarriage-catalog-expansion.js'")&&sw.includes('und097'));
assert.equal(E.validate(JSON.parse(JSON.stringify(late.s))),true,'save do atraso serializável');
console.log('OK: 120 sintomas, 24 rodante, CTS sem leitura falsa, pneu separado, postergação e PCM.');
