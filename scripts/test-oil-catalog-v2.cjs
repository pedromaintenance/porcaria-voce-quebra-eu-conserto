/* Expansão de análises de óleo v2 — invariantes de diagnóstico e retrocompatibilidade. */
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const D=require('../game-data.json'),E=require('../engine.js'),I=require('../phaser-play/inspection.js');
const C=require('../phaser-play/condition-catalog.js'),M=require('../phaser-play/monitoring.js');
const S=require('../phaser-play/sector-views.js'),V=require('../phaser-play/inspection-view.js');
const O=require('../phaser-play/oil-catalog-expansion.js');
assert.equal(O.VERSION,'2.0.0');
assert.equal(C.VERSION,'6.0.0');
assert.equal(C.ENTRIES.length,120);
assert.equal(C.byCategory('oil').length,24);
assert.equal(O.ENTRIES.length,16);
assert.equal(new Set(C.ENTRIES.map(x=>x.id)).size,120,'IDs únicos');
assert.deepEqual(C.ENTRIES.filter(x=>x.category!=='oil').map(x=>x.id).length,96,'outras famílias intactas');
for(let i=1;i<=24;i++){
 const id='OIL'+String(i).padStart(3,'0'),e=C.get(id);
 assert.ok(e,id+' cadastrado');
 assert.equal(e.category,'oil');
 assert.ok(e.compartment&&e.compartment.length>5,id+' compartimento declarado');
 assert.ok(e.indicators.length>0&&e.indicators.every(t=>typeof t==='string'&&t.length>1));
 assert.ok(e.verification.length>25&&e.uncertainty.length>20,id+' verificação e incerteza');
 assert.ok(['acompanhar','revisar_baseline','avaliacao_prioritaria'].includes(e.triage));
 assert.ok(e.sourceKeys.length>0&&e.sourceKeys.every(k=>/^https:\/\/www\.cat\.com\//.test(C.SOURCES[k]||'')),id+' fontes OEM rastreáveis');
 assert.equal(e.followupTool,id==='OIL008'?'REFR':'COLETA','ferramenta correta por fluido');
 assert.equal(e.followupCost,id==='OIL008'?0:40,'custo do caso de arrefecimento preservado');
 assert.ok(e.results.length>=1&&e.results.every(r=>['estavel','inconclusivo','agravamento'].includes(r)));
 assert.ok(D.models.some(m=>m.id===e.modelId),'modelo da frota: '+id);
 assert.ok(!e.escalationScenario||D.scenarios.some(s=>s.id===e.escalationScenario&&s.modelId===e.modelId),'investigação compatível: '+id);
}
assert.ok(Object.isFrozen(C.get('OIL023').indicators),'metadados imutáveis');
const fresh=()=>{const s=E.create(D,()=>.5);I.normalized(s);return s;};
function receiveOne(id){
 const s=fresh();
 s.monitoringFeedSeen=C.byCategory('oil').filter(x=>x.id!==id).map(x=>x.id);
 s.monitoringFeedCursor=0;
 const r=M.receive(s,D,I,{initial:true});
 assert.equal(r.received.length,1,id+' deve chegar pela fonte óleo');
 assert.equal(r.received[0].monitorProtocol,id);
 assert.equal(r.received[0].sourceScenario,null,'sem gabarito antes do PCM');
 return {s,n:r.received[0]};
}
const urgent=receiveOne('OIL023');
assert.equal(urgent.n.priority,'alta','suspeita de arrefecimento no óleo recebe atenção');
assert.equal(M.decide(urgent.s,urgent.n.id,'trend',2).error!==undefined,true,'não adiar triagem prioritária');
const htmlUrgent=V.monitorWidget(urgent.n,urgent.s,M);
assert.ok(htmlUrgent.includes('AVALIAÇÃO PRIORITÁRIA'));
assert.ok(htmlUrgent.includes('data-monitor-action="escalate"'));
assert.ok(!htmlUrgent.includes('data-monitor-action="decide"'));
assert.ok(htmlUrgent.includes('Compartimento:')&&htmlUrgent.includes('Incerteza:'));
const escalated=M.escalate(urgent.s,D,I,urgent.n.id);
assert.equal(escalated.ok,true);
assert.equal(escalated.escalation.sourceScenario,null,'sem roteiro inventado');
assert.equal(escalated.escalation.requiresScenarioMapping,true);
assert.equal(escalated.escalation.priority,'alta');
assert.equal(urgent.s.jobs.length,3,'não cria OS ao escalar');
assert.ok(I.review(urgent.s,escalated.escalation.id,'approve',{},D,E).error,'não autoriza OS sem cenário');
const follow=receiveOne('OIL017');
const escalatedMapped=M.escalate(follow.s,D,I,follow.n.id);
assert.equal(escalatedMapped.ok,true);
assert.equal(escalatedMapped.escalation.sourceScenario,'INC096');
assert.equal(escalatedMapped.escalation.requiresScenarioMapping,false);
const baseline=receiveOne('OIL024');
assert.equal(baseline.n.priority,'baixa');
assert.ok(V.monitorWidget(baseline.n,baseline.s,M).includes('Revisar linha de base'));
assert.equal(M.decide(baseline.s,baseline.n.id,'baseline',2).ok,true);
baseline.s.tools.COLETA=true;
baseline.s.tick+=2;
assert.equal(M.collect(baseline.s,baseline.n.id).sample.trend,'estavel');
assert.equal(M.continueWatch(baseline.s,baseline.n.id,2).ok,true);
baseline.s.tick+=2;
assert.equal(M.collect(baseline.s,baseline.n.id).sample.trend,'estavel');
assert.equal(M.close(baseline.s,baseline.n.id).ok,true,'baseline pode ser encerrado sem OS após 2 resultados');
const unmapped=receiveOne('OIL021');
assert.equal(M.decide(unmapped.s,unmapped.n.id,'sample',2).ok,true);
assert.equal(M.escalate(unmapped.s,D,I,unmapped.n.id).escalation.requiresScenarioMapping,true,'rastreabilidade antes da OS');
const screen=S.monitoring(fresh(),D,M,V,I,E,'oil');
assert.ok(screen.includes('24 ENTRADAS'));
assert.ok(screen.includes('OIL023')&&screen.includes('OIL024'));
assert.ok(screen.includes('Sódio')&&screen.includes('REVISAR LINHA DE BASE'));
const ui=fs.readFileSync('phaser-play/index.html','utf8');
const sw=fs.readFileSync('sw.js','utf8');
assert.ok(ui.indexOf('oil-catalog-expansion.js')<ui.indexOf('condition-catalog.js'));
assert.ok(ui.includes('monitoring.js?v=0.9.8'));
assert.ok(sw.includes("'./phaser-play/oil-catalog-expansion.js'"));
assert.ok(sw.includes('-oil095'));
assert.ok(E.validate(JSON.parse(JSON.stringify(baseline.s))),'save permanece válido após encerrar');
console.log('OK óleo v2: 24 entradas, 16 novas, referências, prioridade PCM, baseline, bloqueio de OS sem cenário e saves.');
