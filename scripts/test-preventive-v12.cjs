/* PORCARIA ciclo 12: preventiva com custo, HH, disputa de recursos e efeito probabilístico. */
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const D=require('../game-data.json'),E=require('../engine.js'),P=require('../phaser-play/preventive.js');
const fresh=()=>E.create(D,()=>0.42);
assert.equal(P.VERSION,'12.0.0');
assert.equal(D.scenarios.length,124);
assert.equal(P.PACKAGES.inspection.hours,2);
assert.equal(P.PACKAGES.service.reduction,0.45);
const s=fresh();
let asset=P.compute(s,D).assets.find(a=>!a.blocked).asset;
const m=s.team[0],before=JSON.stringify(s);
let read=P.compute(s,D);
assert.equal(read.assets.length,D.models.length*6);
assert.equal(JSON.stringify(s),before,'consulta preventiva deve ser imutável');
const oldCash=s.cash;
assert.equal(E.bookPreventive(s,D,asset,m.id,0,'inspection'),null);
assert.equal(s.cash,oldCash-120,'autorizar preventiva deve descontar o caixa imediatamente');
assert.equal(P.compute(s,D).planned,1);
assert.equal(P.risk(s,asset).reduction,0,'reserva não gera efeito antes da execução');
assert.ok(E.bookPreventive(s,D,asset,s.team[1].id,1,'inspection').includes('Conflito'));
const alternative=P.compute(s,D).assets.find(x=>!x.blocked&&x.asset!==asset).asset;
assert.ok(E.bookPreventive(s,D,alternative,m.id,1,'inspection').includes('Conflito'));
assert.ok(E.bookPreventive(s,D,alternative,s.team[1].id,0,'service').includes('Conflito'));
const job=s.jobs[0];
assert.ok(E.bookPreventive(s,D,job.asset,s.team[2].id,2,'inspection').includes('corretiva'));
assert.ok(E.attach(s,job.id,m.id,1,false).includes('preventiva'));
assert.ok(E.scheduleJob(s,D,s.jobs[1].id,m.id,1,s.tick).includes('preventiva'));
const charge=oldCash-120;
assert.equal(E.cancelPreventive(s,s.preventiveJobs[0].id),null);
assert.equal(s.cash,oldCash,'cancelamento devolve o valor integral');
assert.equal(E.cancelPreventive(s,s.preventiveJobs[0].id),'Reserva preventiva ativa não encontrada.');
assert.equal(E.bookPreventive(s,D,asset,m.id,0,'service'),null);
assert.equal(s.cash,oldCash-360,'pacote grande debita o custo correto');
let p=P.compute(s,D);assert.equal(p.planned,1);assert.equal(p.completed,0);
const output=E.advance(s,D,()=>0.95);
assert.equal(s.preventiveJobs.at(-1).status,'completed');
assert.equal(P.compute(s,D).planned,0);
assert.equal(P.compute(s,D).completed,1);
assert.equal(P.compute(s,D).hours,4);
assert.equal(P.compute(s,D).spent,360);
assert.ok(output.hours>=4,'manutenção preventiva consumiu HH do turno');
assert.equal(s.cash,oldCash-360,'gasto da preventiva persiste');
assert.equal(P.risk(s,asset).reduction,0.45,'proteção só após execução');
assert.equal(P.risk(s,asset).expiresTick,9);
assert.equal(P.risk(s,asset,9).reduction,0,'validade temporal definida');
assert.ok(s.decisionHistory.some(x=>x.type==='preventive_authorized'));
assert.ok(s.decisionHistory.some(x=>x.type==='preventive_cancelled'));
assert.ok(s.decisionHistory.some(x=>x.type==='preventive_completed'));
const riskBefore=JSON.stringify(s);
assert.equal(P.screenRandomCandidate(s,asset,()=>0.5),false);
assert.equal(P.screenRandomCandidate(s,asset,()=>0.1),true);
assert.equal(s.preventiveMetrics.screenedRandomCandidates,1);
assert.equal(s.jobs.length,3,'prevenção não remove corretivas existentes');
assert.equal(P.screenRandomCandidate(s,alternative,()=>0),false,'sem proteção não bloqueia falhas por engano');
// Exhaust protection after valid number of virtual shifts.
assert.equal(P.risk(s,asset,s.preventiveEffects.at(-1).expiresTick).reduction,0);
// Old saves remain usable even without any of the new fields.
const legacy=fresh();
delete legacy.preventiveJobs;delete legacy.preventiveEffects;delete legacy.preventiveMetrics;delete legacy.nextPreventive;
assert.equal(E.validate(legacy),true);
assert.equal(P.compute(legacy,D).completed,0);
const freeAsset=P.compute(legacy,D).assets.find(a=>!a.blocked).asset;
assert.equal(E.bookPreventive(legacy,D,freeAsset,legacy.team[0].id,0,'inspection'),null);
assert.equal(E.validate(JSON.parse(JSON.stringify(legacy))),true);
const low=fresh();low.cash=0;
assert.ok(E.bookPreventive(low,D,P.compute(low,D).assets.find(a=>!a.blocked).asset,low.team[0].id,0,'inspection').includes('Caixa'));
assert.equal(low.preventiveJobs.length,0);
const html=fs.readFileSync('phaser-play/index.html','utf8'),ui=fs.readFileSync('phaser-play/game.js','utf8'),sw=fs.readFileSync('sw.js','utf8');
assert.ok(ui.includes("await import('./preventive.js?v=0.9.15')"),'Phaser carrega o módulo');
assert.ok(ui.includes('function drawPreventive()')&&ui.includes('data-preventive-book')&&ui.includes('data-preventive-cancel'));
assert.ok(ui.includes('data-planning-horizon="preventive"'));
assert.ok(sw.includes('preventive0915')&&sw.includes("'./phaser-play/preventive.js'"));
assert.ok(html.includes('game.js?v=0.9.13'),'URLs de cache anteriores preservadas para os testes legados');
console.log('OK v12: custos, reserva, cancelamento, HH, caixas, conflitos PCM, janela probabilística e save legado.');
