/* Ciclo 15: standby, utilização, liberação parcial e migração da telemetria V14. */
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const D=require('../game-data.json'),E=require('../engine.js');
const F=require('../phaser-play/fleet-telemetry.js');
const VIEW=require('../phaser-play/fleet-view.js');
assert.equal(F.VERSION,'15.0.0');
assert.deepEqual(F.DUTY_CHOICES,[0,4,8,12]);
const newGame=()=>E.create(D,()=>0.45);
const s=newGame(),ids=F.assetIDs(D);
assert.equal(ids.length,54);
assert.equal(s.fleetTelemetry.policyStartedTick,0);
assert.ok(ids.every(id=>s.fleetTelemetry.dutyHours[id]===8),'novos ativos operam 8 h virtuais/turno');
assert.ok(E.setFleetDuty(s,D,ids[0],9).includes('Jornada'),'jornada inválida rejeitada');
assert.ok(E.setFleetDuty(s,D,'EQ99·99',8).includes('Ativo'),'id de fora da frota rejeitado');
const before=JSON.stringify(s);
const view=F.compute(s,D);
assert.equal(view.metrics.operationalAvailabilityPct,null,'sem turnos não há porcentagem');
assert.equal(JSON.stringify(s),before,'consulta de KPIs deve ser pura');
E.advance(s,D,()=>0.95);
const tick=s.fleetTelemetry.samples[0];
assert.equal(tick.tick,0);
assert.equal(tick.operating,408);
assert.equal(tick.standby,204);
assert.equal(tick.corrective,36);
assert.equal(tick.preventive,0);
assert.equal(tick.operating+tick.standby+tick.corrective+tick.preventive,648);
assert.equal(tick.perAsset.length,54);
assert.ok(tick.perAsset.every(x=>Math.abs(x.operating+x.standby+x.corrective+x.preventive-12)<0.001));
let rep=F.compute(s,D);
assert.equal(rep.metrics.operationalAvailabilityPct,94.4);
assert.equal(rep.metrics.effectiveUtilizationPct,66.7);
assert.equal(rep.metrics.occupancyPct,63);
assert.equal(rep.metrics.theoreticalHours,648);
assert.equal(rep.coverage.sampledTicks,1);
assert.equal(rep.coverage.complete,false);
const free=ids.find(id=>!s.jobs.some(j=>j.asset===id));
assert.ok(free);
assert.equal(E.setFleetDuty(s,D,free,0),null);
assert.ok(s.decisionHistory.some(x=>x.type==='fleet_duty_changed'&&x.asset===free));
assert.equal(s.fleetTelemetry.dutyHours[free],0);
const noChange=s.decisionHistory.length;
assert.equal(E.setFleetDuty(s,D,free,0),null);
assert.equal(s.decisionHistory.length,noChange,'ajuste igual não duplica evento');
assert.equal(F.projected(s,free),'standby');
E.advance(s,D,()=>0.95);
const second=s.fleetTelemetry.samples[1].perAsset.find(x=>x.asset===free);
assert.equal(second.operating,0);
assert.equal(second.standby,12);
assert.equal(s.fleetTelemetry.assets[free].hourmeter,8,'horímetro não cresce com standby');
assert.equal(s.fleetTelemetry.assets[free].standbyHours,16);
rep=F.compute(s,D);
assert.ok(VIEW.render(rep,'EQ01').includes('data-fleet-duty'));
assert.ok(VIEW.render(rep,'EQ01').includes('Standby virtual'));
// Parada preventiva de 4 horas com jornada zero: 4 horas de parada + 8 standby, sem operação.
const pm=newGame(),fpm=ids.find(id=>!pm.jobs.some(j=>j.asset===id)&&
 !pm.preventiveOrders.some(j=>j.asset===id&&j.status!=='completed'));
assert.equal(E.setFleetDuty(pm,D,fpm,0),null);
assert.equal(E.bookPreventive(pm,D,fpm,pm.team[0].id,0,'service'),null);
E.advance(pm,D,()=>0.95);
const sample=pm.fleetTelemetry.samples[0].perAsset.find(x=>x.asset===fpm);
assert.deepEqual([sample.operating,sample.standby,sample.preventive,sample.corrective],[0,8,4,0]);
assert.equal(pm.fleetTelemetry.assets[fpm].hourmeter,0);
// Conclusão de corretiva no turno: admite parada parcial de acordo com HH de reparo deste turno.
const cm=newGame(),order=cm.jobs[0],mechanic=cm.team[0],sc=E.scenario(D,order.scene);
cm.tools[sc.tool]=true;cm.stock[sc.material]=Math.max(2,cm.stock[sc.material]||0);
order.stage=6;order.repairRemaining=1;order.diagRemaining=0;
assert.equal(E.attach(cm,order.id,mechanic.id,0,false),null);
E.advance(cm,D,()=>0.99);
assert.equal(cm.jobs.some(j=>j.id===order.id),false,'OS foi concluída');
const cSample=cm.fleetTelemetry.samples[0].perAsset.find(x=>x.asset===order.asset);
assert.ok(cSample.corrective>0&&cSample.corrective<12,'liberação parcial de corretiva');
assert.equal(cSample.operating+cSample.standby+cSample.corrective+cSample.preventive,12);
assert.ok(cm.fleetTelemetry.assets[order.asset].hourmeter>0,'retorno à operação permite horímetro parcial');
assert.equal(cm.fleetTelemetry.assets[order.asset].lastState,'corrective_partial');
// Compatibilidade com V14: não reclassificar amostra antiga, preservar acumulado OEM NÃO REAL.
const legacy=newGame();
legacy.fleetTelemetry.version='14.0.0';
legacy.fleetTelemetry.samples=[{tick:0,operating:608,corrective:36,preventive:4}];
legacy.fleetTelemetry.throughTick=1;legacy.tick=1;legacy.day=1;legacy.shift=1;
legacy.fleetTelemetry.assets[free].hourmeter=8;
delete legacy.fleetTelemetry.policyStartedTick;delete legacy.fleetTelemetry.dutyHours;
const saved=legacy.fleetTelemetry.assets[free].hourmeter;
E.initFleet(legacy,D);
assert.equal(legacy.fleetTelemetry.policyStartedTick,1);
assert.equal(legacy.fleetTelemetry.dutyHours[free],12,'legado mantém premissa anterior');
assert.equal(legacy.fleetTelemetry.assets[free].hourmeter,saved);
assert.equal(F.compute(legacy,D).metrics.theoreticalHours,0,'não misturar períodos metodológicos');
const snapshot=JSON.stringify(legacy);E.initFleet(legacy,D);
assert.equal(JSON.stringify(legacy),snapshot,'migração idempotente');
E.advance(legacy,D,()=>0.95);
assert.equal(legacy.fleetTelemetry.samples.length,2);
assert.equal(F.compute(legacy,D).coverage.sampledTicks,1,'janela inclui só V15');
const once=F.advance(legacy,D);
assert.ok(!once.error);
const no=F.advance(legacy,D);
assert.ok(no.error,'segunda leitura do mesmo turno é rejeitada');
assert.equal(E.validate(JSON.parse(JSON.stringify(legacy))),true);
const ui=fs.readFileSync('phaser-play/game.js','utf8'),sw=fs.readFileSync('sw.js','utf8');
assert.ok(ui.includes('data-fleet-duty'));
assert.ok(ui.includes('E.setFleetDuty('));
assert.ok(ui.includes("await import('./fleet-telemetry.js?v=0.9.18')"));
assert.ok(ui.includes("await import('./fleet-view.js?v=0.9.18')"));
assert.ok(sw.includes('standby0918'));
console.log('OK ciclo 15: standby, utilização, 12h/ativo, preventiva, corretiva parcial, jornada, auditoria e save V14.');
