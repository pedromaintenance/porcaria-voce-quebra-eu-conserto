/* Sessão 9: monitoramento, recoleta, tendência e escalonamento sem OS automática. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const D=require('../game-data.json'),E=require('../engine.js'),I=require('../phaser-play/inspection.js');
const M=require('../phaser-play/monitoring.js'),V=require('../phaser-play/inspection-view.js');
assert.equal(D.scenarios.length,124,'missões anteriores preservadas');
assert.equal(D.paths.length,493,'sem alterar locações funcionais');
assert.equal(Object.keys(M.PROTOCOLS).length,3,'três estudos-piloto');
for(const [id,p] of Object.entries(M.PROTOCOLS)){
 assert.ok(D.models.some(m=>m.id===p.modelId),id+' modelo cadastrado');
 assert.ok(D.scenarios.some(sc=>sc.id===p.escalationScenario&&sc.modelId===p.modelId),id+' cenário de investigação válido');
 assert.ok(p.baseline.length>40&&p.results.length>0);
}
const fresh=()=>{const s=E.create(D,()=>.5);I.normalized(s);return s};
const initial=fresh();
const oldJobs=initial.jobs.map(j=>j.id);
let opened=M.open(initial,D,I,'baseline');
assert.equal(opened.ok,true);
let note=opened.notification;
assert.equal(note.status,'aguarda_revisao_pcm');
assert.equal(note.monitorOnly,true);
assert.equal(note.sourceScenario,null,'registro de tendência não é defeito com gabarito');
assert.equal(note.workOrderId,null);
assert.deepEqual(initial.jobs.map(j=>j.id),oldJobs,'nenhuma OS criada no início');
assert.equal(I.review(initial,note.id,'approve',{scope:'Investigar sintomas reportados e programar execução.',trade:'mecanica',estimatedHH:2},D,E).error!==undefined,true,'não aprovar nota de monitoramento como OS');
assert.equal(M.decide(initial,note.id,'invalid',2).error!==undefined,true,'justificativa obrigatória');
assert.equal(M.decide(initial,note.id,'baseline',3).error!==undefined,true,'intervalo de turno válido');
assert.equal(M.decide(initial,note.id,'baseline',2).ok,true);
assert.equal(note.status,'monitorando');
assert.equal(note.monitoring.nextTick,initial.tick+2);
assert.equal(note.workOrderId,null);
assert.equal(M.summary(initial).active,1);
const tickAtStart=initial.tick;
assert.equal(M.collect(initial,note.id).error!==undefined,true,'recoleta não antecipada');
assert.equal(note.monitoring.samples.length,0);
const availableJobs=new Set(initial.jobs.map(j=>j.asset));
assert.ok(!availableJobs.has(note.asset),'monitoramento não coincide com OS ativa');
const snapshot=JSON.parse(JSON.stringify(initial));
assert.equal(E.validate(snapshot),true,'save v1.1.0 com monitoramento válido');
assert.equal(snapshot.notifications.find(n=>n.id===note.id).monitoring.nextTick,tickAtStart+2);
const otherGame=fresh();
I.normalized(otherGame);
const active=M.open(otherGame,D,I,'sample').notification;
assert.equal(M.decide(otherGame,active.id,'sample',2).ok,true);
otherGame.jobs=[];
const blockedAsset=active.asset;
const oldScenes=otherGame.jobs.length;
E.spawn(otherGame,D,12,()=>.1);
assert.equal(otherGame.jobs.filter(j=>j.asset===blockedAsset).length,0,'sorteio normal não gera OS em ativo monitorado');
assert.ok(otherGame.jobs.length>=oldScenes);
initial.tick=tickAtStart+2;
assert.equal(M.summary(initial).due,1);
const cashBefore=initial.cash;
initial.tools.COLETA=false;
assert.equal(M.collect(initial,note.id).error!==undefined,true,'kit de coleta obrigatório');
assert.equal(initial.cash,cashBefore,'não cobrar teste recusado');
initial.tools.COLETA=true;
const first=M.collect(initial,note.id);
assert.equal(first.ok,true);
assert.equal(first.sample.trend,'estavel');
assert.equal(initial.cash,cashBefore-40);
assert.equal(note.monitoring.status,'aguarda_decisao');
assert.equal(M.summary(initial).due,0);
assert.equal(M.close(initial,note.id).error!==undefined,true,'uma só coleta não encerra');
assert.equal(M.collect(initial,note.id).error!==undefined,true,'sem recoleta duplicada');
assert.equal(M.continueWatch(initial,note.id,2).ok,true);
initial.tick+=2;
const second=M.collect(initial,note.id);
assert.equal(second.sample.trend,'estavel');
assert.equal(note.monitoring.samples.length,2);
assert.equal(M.close(initial,note.id).ok,true);
assert.equal(note.status,'encerrada_monitoramento');
assert.equal(note.monitoring.nextTick,null);
assert.equal(M.summary(initial).closed,1);
assert.equal(note.workOrderId,null,'duas coletas estáveis -> sem OS');
assert.deepEqual(initial.jobs.map(j=>j.id),oldJobs);
assert.equal(M.collect(initial,note.id).error!==undefined,true,'não recoletar após encerramento');
const uncertain=fresh();
const n2=M.open(uncertain,D,I,'sample').notification;
assert.equal(M.decide(uncertain,n2.id,'sample',2).ok,true);
uncertain.tick+=2;
const inconclusive=M.collect(uncertain,n2.id);
assert.equal(inconclusive.sample.trend,'inconclusivo');
assert.equal(M.close(uncertain,n2.id).error!==undefined,true,'inconclusivo não encerra');
assert.equal(M.continueWatch(uncertain,n2.id,2).ok,true);
uncertain.tick+=2;
const worse=M.collect(uncertain,n2.id);
assert.equal(worse.sample.trend,'agravamento');
assert.equal(n2.monitoring.status,'requer_avaliacao');
assert.equal(M.continueWatch(uncertain,n2.id,2).error!==undefined,true,'agravamento não permite simples continuidade');
assert.equal(M.summary(uncertain).attention,1);
const beforeEscalate=uncertain.jobs.length;
const raised=M.escalate(uncertain,D,I,n2.id);
assert.equal(raised.ok,true);
assert.equal(raised.escalation.status,'aguarda_revisao_pcm');
assert.equal(raised.escalation.priority,'alta');
assert.equal(raised.escalation.sourceScenario,'INC042');
assert.equal(raised.escalation.asset,n2.asset);
assert.equal(raised.escalation.previousMonitorId,n2.id);
assert.equal(n2.status,'escalonada_monitoramento');
assert.equal(n2.escalationNotificationId,raised.escalation.id);
assert.equal(uncertain.jobs.length,beforeEscalate,'escalonamento cria notificação, nunca OS');
assert.equal(M.escalate(uncertain,D,I,n2.id).error!==undefined,true,'não duplicar escalonamento');
const scenario=D.scenarios.find(x=>x.id===raised.escalation.sourceScenario);
const diagnoses=[...scenario.path,scenario.component,scenario.damage,scenario.cause];
const plan=I.review(uncertain,raised.escalation.id,'approve',{diagnosis:diagnoses,action:'diagnosticar',trade:'lubrificacao',estimatedHH:4},D,E);
assert.equal(plan.ok,true,'nova nota segue ao PCM regular');
assert.equal(uncertain.jobs.length,beforeEscalate);
const conversion=I.commitConversion(uncertain,D,E,raised.escalation.id);
assert.equal(conversion.ok,true,'OS somente após aprovação e conversão explícitas');
assert.equal(conversion.order.asset,n2.asset);
assert.equal(uncertain.jobs.length,beforeEscalate+1);
const severe=fresh(),n3=M.open(severe,D,I,'differential').notification;
assert.equal(M.decide(severe,n3.id,'trend',4).ok,true);
severe.tick+=4;
assert.equal(M.collect(severe,n3.id).sample.trend,'agravamento');
assert.equal(M.escalate(severe,D,I,n3.id).escalation.sourceScenario,'INC092');
const view=V.render(initial,D,I,E,null,M);
assert.ok(view.includes('MONITORAMENTOS ATIVOS'),'monitoramentos seguem resumidos sem estudos de teste');
assert.ok(view.includes('RECOLETAS VENCIDAS'));
assert.ok(view.includes('ENCERRADO SEM OS')||view.includes('Monitoramento didático encerrado'));
assert.ok(!view.includes('data-monitor-start="baseline"'),'botões de teste não aparecem mais');
assert.ok(!view.includes('<textarea'),'revisão sem digitação livre de hipóteses');
const html=fs.readFileSync(path.join(__dirname,'../phaser-play/index.html'),'utf8');
assert.ok(html.includes('monitoring.js?v=0.9.18-copy1'),'script carregado');
const game=fs.readFileSync(path.join(__dirname,'../phaser-play/game.js'),'utf8');
assert.ok(game.includes('M.receive(state,data,I)')&&game.includes('M.collect(state,id)'),'chegada automática e ações ligadas ao jogo');
const sw=fs.readFileSync(path.join(__dirname,'../sw.js'),'utf8');
assert.ok(sw.includes("'./phaser-play/monitoring.js'"),'módulo offline');
const legacy=fresh();
delete legacy.notifications;delete legacy.inspections;
I.normalized(legacy);
assert.deepEqual(M.summary(legacy),{total:0,active:0,due:0,attention:0,closed:0,escalated:0});
assert.equal(E.validate(legacy),true,'saves antigos permanecem utilizáveis');
console.log('OK sessão 9: 100 missões, monitoramento sem OS, recoletas, piora, escalonamento, PCM, patrimônio e saves.');
