/* PORCARIA — sala de rádio do Elton integrada à Fila de OS. */
'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const base=path.resolve(__dirname,'..');
const asset=path.join(base,'phaser-play/assets/elton-sala-radio.webp');
const image=fs.readFileSync(asset);
assert.ok(image.length>150000,'arte do Elton deve existir em resolução útil');
assert.equal(image.toString('ascii',0,4),'RIFF','arquivo WebP: assinatura RIFF');
assert.equal(image.toString('ascii',8,12),'WEBP','arquivo WebP válido');
assert.equal(image.readUInt32LE(4)+8,image.length,'arquivo completo e não truncado');
const html=fs.readFileSync(path.join(base,'phaser-play/index.html'),'utf8');
const radio=html.match(/<section class="panel" data-panel="queue">([\s\S]*?)<section class="panel" data-panel="inspection">/)?.[1];
assert.ok(radio,'seção da fila preservada');
assert.ok(radio.includes('assets/elton-sala-radio.webp'),'imagem carregada na Fila de OS');
assert.ok(radio.includes('alt="Elton recebendo chamadas pelo rádio'),'imagem com descrição acessível');
assert.ok(radio.includes('id="radioQueueSummary"'),'placar do rádio no setor correto');
assert.ok(radio.includes('id="queueSearch"')&&radio.includes('id="queueFilter"'),'pesquisa/filtros existentes preservados');
assert.ok(radio.includes('id="queue"'),'lista de OS continua presente');
assert.ok(radio.indexOf('radioDispatchScene')<radio.indexOf('queueToolbar'),'hero acima da fila, sem ocultar controles');
assert.ok(html.includes('.radioDispatchScene>img{')&&html.includes('aspect-ratio:1672/941'),'proporções da arte preservadas');
assert.ok(html.includes('game.js?v=0.8.32-pt1412-inspection3-monitor9-sectors1-eltonradio1'),'script sem cache antigo');
const game=fs.readFileSync(path.join(base,'phaser-play/game.js'),'utf8');
assert.ok(game.includes("function renderQueue(){"),'fluxo original preservado');
assert.ok(game.includes("const radioSummary=$('radioQueueSummary')"),'placar recebe dados ativos');
assert.ok(game.includes("calls.filter(j=>j.priority===3).length"),'críticos vêm das OS reais');
assert.ok(game.includes("calls.filter(j=>!j.assigned).length"),'pendentes vêm da fila real');
assert.ok(game.includes("calls.filter(j=>!!j.assigned).length"),'alocados vêm da fila real');
assert.ok(game.includes("FILTER.queue==='all'")&&game.includes('data-pick="${j.id}"'),'filtros e abertura de OS mantidos');
const sw=fs.readFileSync(path.join(base,'sw.js'),'utf8');
assert.ok(sw.includes("'./phaser-play/assets/elton-sala-radio.webp'"),'imagem disponível no PWA offline');
assert.ok(sw.includes('-eltonradio1'),'cache versionado');
console.log('OK: asset do Elton, Fila de OS, placar dinâmico, busca, responsividade e cache PWA.');
