/* Ciclo 9: histórico de decisões PCM / Supervisor e comparações sem causalidade imaginada. */
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const D=require('../game-data.json'),E=require('../engine.js'),I=require('../phaser-play/inspection.js');
const C=require('../phaser-play/condition-catalog.js'),M=require('../phaser-play/monitoring.js');
const L=require('../phaser-play/decision-ledger.js');
assert.equal(L.VERSION,'9.0.0');
const newState=()=>{const s=E.create(D,()=>.5);I.normalized(s);return s};
const s=newState(),original=JSON.stringify(s);
const start=L.compute(s,D);
assert.equal(JSON.stringify(s),original,'histórico não altera save');
assert.equal(start.metrics.recordedEvents,0);
assert.equal(start.metrics.completed,0);
assert.equal(start.metrics.purchases,0);
assert.deepEqual(start.timeline,[]);
assert.equal(E.validate(s),true);
const p=D.scenarios.find(x=>x.id==='INC101');
assert.equal(E.orderMaterial(s,D,p.material,2,true,()=>.5),null);
assert.equal(s.decisionHistory.length,1);
assert.equal(s.decisionHistory[0].type,'purchase');
assert.equal(s.decisionHistory[0].fast,true);
assert.equal(s.decisionHistory[0].purchaseId,s.purchaseHistory[0].id);
assert.equal(s.decisionHistory[0].demandAtPurchase,0,'compra antecipada não é declarada erro');
assert.equal(L.compute(s,D).metrics.earlyWithoutDiagnosedDemand,1);
assert.equal(L.compute(s,D).metrics.urgentPurchases,1);
const during=L.compute(s,D,{filter:'supply'});
assert.equal(during.timeline.length,1);
assert.equal(during.timeline[0].label,'Compra');
E.advance(s,D,()=>.5);
assert.equal(s.purchaseHistory[0].receivedTick,1);
assert.equal(s.decisionHistory[1].type,'receipt');
assert.equal(L.compute(s,D).metrics.receipts,1);
const j=s.jobs.find(x=>!x.assigned);
assert.ok(j);
const m=s.team[0];m.restAt=null;m.assigned=null;
assert.equal(E.attach(s,j.id,m.id,0,false),null);
const allocation=s.decisionHistory.at(-1);
assert.equal(allocation.type,'allocation');
assert.equal(allocation.orderId,j.id);
assert.equal(allocation.mechanicId,m.id);
assert.equal(allocation.bay,0);
assert.equal(E.attach(s,j.id,m.id,0,false),null);
assert.equal(s.decisionHistory.at(-1).type,'allocation','realocação explicitamente autorizada é registrada');
const allEvents=L.compute(s,D).timeline;
assert.ok(allEvents[0].seq>allEvents.at(-1).seq,'mais recentes primeiro');
assert.ok(L.compute(s,D,{filter:'execution'}).timeline.every(x=>x.group==='execution'));
assert.ok(L.compute(s,D,{filter:'pcm'}).timeline.every(x=>x.group==='pcm'));
assert.ok(L.compute(s,D,{filter:'supply'}).timeline.every(x=>x.group==='supply'));
assert.equal(L.compute(s,D,{filter:'INVALID'}).filter,'all');
assert.equal(L.compute(s,D,{limit:1}).timeline.length,1);
// Exercitar aprovação PCM e conversão na trilha (sem geração automática de OS).
const t=newState();t.jobs=[];t.monitoringFeedCursor=3;
t.monitoringFeedSeen=C.byCategory('fps').filter(x=>x.id!=='FPS006').map(x=>x.id);
const incoming=M.receive(t,D,I,{initial:true}).received[0];
assert.equal(incoming.monitorProtocol,'FPS006');
const raised=M.escalate(t,D,I,incoming.id);
assert.equal(raised.ok,true);
// Fixture isolada: a classificação FPS real ainda não tem subgrupo comprovado na 1412.
 // O teste do ledger usa temporariamente uma localização SAP existente, SEM alterar D.
const note=raised.escalation,tData=structuredClone(D);
const sc=tData.scenarios.find(x=>x.id===note.sourceScenario);
const valid=tData.sapInstalledPaths.find(x=>x.modelId===sc.modelId);
assert.ok(valid,'fixture de PCM exige uma tripla de instalação real');
sc.path=[valid.system,valid.group,valid.subgroup];
sc.sapPathMapping={status:'validado_na_planilha',previousPath:sc.sapPathMapping.previousPath};
sc.sapPartMapping.status='equivalencia';
assert.ok(I.review(t,note.id,'approve',{scope:'Verificar em segurança e documentar evidências de retenção do FPS instalado.',trade:'mecanica',estimatedHH:4},tData,E).error,'sem diagnóstico não aprova FPS');
assert.equal(t.decisionHistory.length,0,'reprovações não ficam como decisão validada');
const diagnosis=[...sc.path,sc.component,sc.damage,''];
const review=I.review(t,note.id,'approve',{diagnosis,action:'verificar',trade:'mecanica',estimatedHH:4,reason:'Roteiro didático para revisão técnica.'},tData,E);
assert.equal(review.ok,true,JSON.stringify(review));
assert.equal(t.decisionHistory[0].type,'pcm_review');
assert.equal(t.decisionHistory[0].estimatedHH,4);
assert.equal(t.jobs.length,0);
const conversion=I.commitConversion(t,tData,E,note.id);
assert.equal(conversion.ok,true);
assert.equal(t.decisionHistory[1].type,'pcm_conversion');
assert.equal(t.decisionHistory[1].orderId,conversion.order.id);
assert.equal(L.compute(t,D).metrics.pcmReviews,1);
assert.equal(L.compute(t,D).metrics.createdOrders,1);
assert.equal(I.commitConversion(t,D,E,note.id).ok,undefined,'sem converter em duplicidade');
assert.equal(t.decisionHistory.length,2,'sem registro duplicado após falha');
// Simular conclusão observada, com diferença entre HH previstas e efetivamente trabalhadas.
const finished={...conversion.order,finishedTick:4,elapsedHours:48,worked:8.5,reworkHours:2,
 plannerDiagnosis:{...conversion.order.plannerDiagnosis,errorCount:2},firstTime:false};
t.jobs=[];t.done=[finished];
const summary=L.compute(t,D);
assert.equal(summary.metrics.closedWithApprovedPlan,1);
assert.equal(summary.plans[0].plannedHH,4);
assert.equal(summary.plans[0].workedHH,8.5);
assert.equal(summary.plans[0].effortDifferenceHH,4.5);
assert.equal(summary.plans[0].downtimeHours,48);
assert.equal(summary.metrics.recordedReworkHours,2);
assert.equal(summary.metrics.reworkOnOrdersWithPlannerError,2);
assert.ok(summary.interpretation.includes('não é integralmente causado'),'sem atribuir causalidade');
assert.ok(summary.interpretation.includes('estoque estratégico'));
const snapshot=JSON.stringify(t);
assert.equal(L.compute(t,D,{filter:'pcm'}).timeline.length,2);
assert.equal(JSON.stringify(t),snapshot);
// Registrar avaliação de plano no motor, não apenas sintetizar campo histórico.
const validScenario=D.scenarios.find(x=>E.sapEligible(D,x)&&x.modelId==='EQ01');
assert.ok(validScenario,'fixture de avaliação exige caminho verificado na 1412');
const e=newState();e.jobs=[];e.stock[validScenario.material]=2;e.tools[validScenario.tool]=true;
const stageJob={id:'OS9001',scene:validScenario.id,modelId:validScenario.modelId,asset:validScenario.modelId+'·99',priority:validScenario.priority,
 status:'diagnostico',tickOpen:0,dayOpen:1,stage:0,assigned:null,bay:null,help:false,wrong:0,rework:false,
 diagRemaining:4,repairRemaining:4,worked:0,toolWait:0,blockedShifts:0,reworkHours:0,
 plannerDiagnosis:{codes:[...validScenario.path,validScenario.component,validScenario.damage,''],evaluated:false},materialUsed:false};
e.jobs.push(stageJob);for(const x of e.team)x.assigned=null;
assert.equal(E.attach(e,stageJob.id,e.team[0].id,0,false),null);
E.advance(e,D,()=>.5);
const evaluated=e.decisionHistory.find(x=>x.type==='planner_evaluation');
assert.ok(evaluated);assert.equal(evaluated.errors,0);
assert.equal(evaluated.perfect,false,'causa em branco não equivale à conclusão completa');
assert.equal(L.compute(e,D).metrics.evaluatedPlans,1);
// Simular save legado sem novos campos, sem mutações.
const legacy=newState();delete legacy.decisionHistory;delete legacy.nextDecision;delete legacy.purchaseHistory;
const clean=JSON.stringify(legacy);
assert.equal(L.compute(legacy,D).metrics.recordedEvents,0);
assert.equal(JSON.stringify(legacy),clean);
E.recordDecision(legacy,'allocation',{orderId:'LEG-1'});
assert.equal(legacy.decisionHistory[0].seq,1);
for(let i=0;i<405;i++)E.recordDecision(legacy,'receipt',{purchaseId:'TEST-'+i});
assert.equal(legacy.decisionHistory.length,400,'histórico limitado a 400 eventos');
assert.ok(legacy.decisionHistory[0].seq>1);
assert.equal(new Set(legacy.decisionHistory.map(x=>x.id)).size,400);
assert.equal(E.validate(JSON.parse(JSON.stringify(legacy))),true);
const html=fs.readFileSync('phaser-play/index.html','utf8'),ui=fs.readFileSync('phaser-play/game.js','utf8'),sw=fs.readFileSync('sw.js','utf8');
assert.ok(html.indexOf('decision-ledger.js?v=0.9.12')<html.indexOf('game.js?v='));
assert.ok(ui.includes('function drawDecisionHistory()'));
assert.ok(ui.includes('data-decision-filter'));
assert.ok(ui.includes('HISTÓRICO DE DECISÕES'));
assert.ok(sw.includes("'./phaser-play/decision-ledger.js'")&&sw.includes('ledger0912'));
console.log('OK ciclo 9: eventos, histórico de compras, PCM, comparação HH, filtros, limite, saves legados e UI.');
