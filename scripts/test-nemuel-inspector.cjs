/* Nemuel, inspetor titular — 70 em todas as habilidades, 50 nas Sandvik. */
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const E=require('../engine.js'),I=require('../phaser-play/inspection.js'),D=require('../game-data.json');
const root=path.resolve(__dirname,'..');
const sheet=path.join(root,'phaser-play/assets/characters/nemuel-inspetor-4poses-v2.png');
const raw=fs.readFileSync(sheet);
assert.ok(raw.length>100000,'arte de alta resolução');
assert.equal(raw.subarray(0,8).toString('hex'),'89504e470d0a1a0a');
assert.deepEqual([raw.readUInt32BE(16),raw.readUInt32BE(20)],[1211,1299],'atlas original irregular');
assert.equal(raw[25],6,'cartela RGBA com transparência');
const matrix=E.baselineSkills('nemuel');
for(const group of E.SKILL_GROUPS)for(const entry of E.SKILL_CATALOG[group]){
 const wanted=group==='machines'&&['EQ05','EQ06'].includes(entry.id)?50:70;
 assert.equal(matrix[group][entry.id],wanted,group+'/'+entry.id);
}
const s=E.create(D,()=>.42);
const nemuel=s.team.find(m=>m.name==='Nemuel');
assert.ok(nemuel,'Nemuel no elenco inicial');
assert.equal(nemuel.sprite,'nemuel');
assert.equal(nemuel.role,'inspecao');
assert.equal(nemuel.specialty,'Inspetor');
assert.equal(nemuel.skill,70,'habilidade histórica coerente');
assert.equal(nemuel.id,'M5');
assert.equal(s.team.length,5);
assert.deepEqual(nemuel.competencies,matrix);
assert.equal(E.COMPETENCY.evaluate(nemuel,D.scenarios.find(c=>c.modelId==='EQ05')).machine,50);
assert.equal(E.COMPETENCY.evaluate(nemuel,D.scenarios.find(c=>c.modelId==='EQ06')).machine,50);
assert.equal(E.COMPETENCY.evaluate(nemuel,D.scenarios.find(c=>c.modelId==='EQ01')).machine,70);
const free=D.models.flatMap(m=>Array.from({length:6},(_,i)=>m.id+'·'+String(i+1).padStart(2,'0')))
 .find(asset=>!s.jobs.some(j=>j.asset===asset));
assert.ok(free);
const scheduled=I.schedule(s,D,free,nemuel.id);
assert.equal(scheduled.ok,true,'pode ser selecionado para inspeção');
assert.equal(scheduled.inspection.inspectorId,nemuel.id);
assert.equal(scheduled.inspection.estimatedHH,1.5);
const before=JSON.stringify(s);
E.normalizeRoster(s);
assert.equal(JSON.stringify(s),before,'normalização repetida não duplica');
const old=E.create(D,()=>.50);
const original=old.team.filter(m=>m.sprite!=='nemuel');
old.team=original;
old.nextPerson=6;
const jobSnapshot=JSON.stringify(old.jobs),oldIds=old.team.map(m=>m.id);
E.normalizeRoster(old);
assert.deepEqual(old.team.slice(0,4).map(m=>m.id),oldIds,'IDs dos antigos preservados');
assert.equal(JSON.stringify(old.jobs),jobSnapshot,'OS intactas');
assert.equal(old.team.filter(m=>m.sprite==='nemuel').length,1);
assert.equal(old.team.find(m=>m.sprite==='nemuel').id,'M6','migração usa ID livre');
assert.equal(old.nextPerson,7);
const previous=JSON.stringify(old);
E.normalizeRoster(old);
assert.equal(JSON.stringify(old),previous,'migração idempotente');
const game=fs.readFileSync(path.join(root,'phaser-play/game.js'),'utf8');
assert.ok(game.includes("nemuel:'./assets/characters/nemuel-inspetor-4poses-v2.png'"),'sprite registrado no Phaser');
assert.ok(game.includes('const WORKER_RENDER_FRAME={width:290,height:311}'),'saída de renderização preservada');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
assert.ok(sw.includes("'./phaser-play/assets/characters/nemuel-inspetor-4poses-v2.png'"),'PWA inclui inspetor');
assert.ok(sw.includes('-nemuel1'),'cache atualizado');
console.log('OK: Nemuel inspetor titular, competências 70/50 Sandvik, atlas RGBA, inspeções, saves e PWA.');
