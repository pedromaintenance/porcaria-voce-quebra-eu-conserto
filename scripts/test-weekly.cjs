/* P.O.R.C.A.R.I.A. — testes da visão semanal de capacidade. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const engine=require(path.join(root,'engine.js'));
const weekly=require(path.join(root,'phaser-play','weekly.js'));
const data=JSON.parse(fs.readFileSync(path.join(root,'game-data.json'),'utf8'));
const state=engine.create(data,()=>0.42);
const snapshot=JSON.stringify(state);
let w=weekly.calculate(state,data);
assert.equal(JSON.stringify(state),snapshot,'quadro semanal não pode modificar save ou avançar turno');
assert.equal(w.ticks.length,14,'14 turnos deslizantes');
assert.equal(w.horizonHours,168,'14 × 12h corridas');
assert.equal(w.capacitySlots,3,'limitante de slots: boxes ou mecânicos');
assert.equal(w.capacityHH,441,'3 boxes × 10,5h × 14 turnos de capacidade útil');
assert.equal(w.receiptCount,0,'sem pedidos não há entregas');
assert.equal(w.fixedWageReference,7*(state.team.length*220+180),'folha fixa 7 viradas do dia no horizonte iniciado no turno A');
assert.equal(w.ticks[0].day,1);
assert.equal(w.ticks[0].shift,'A');
assert.equal(w.ticks[1].day,1);
assert.equal(w.ticks[1].shift,'B');
assert.equal(w.ticks[2].day,2);
assert.equal(w.ticks[2].shift,'A');
assert.equal(w.awaitingDiagnosis,state.jobs.length,'todas começam com diagnóstico pendente');
assert.equal(w.diagnosed,0);
assert.equal(w.pendingDiagnosticStages,state.jobs.length*6,'etapas em vez de diagnostico em HH fictícias');
assert.equal(w.materials.length,0,'não revelar peça de falha ainda não diagnosticada');
assert.ok(w.repairEquivalentHours>0,'esforço de reparo separado dos diagnósticos');
const rested=state.team[0];
rested.restAt=state.tick;
state.team.slice(3).forEach(m=>m.restAt=state.tick);
w=weekly.calculate(state,data);
assert.equal(w.ticks[0].grossHH,21,'quatro descansos deixam duas pessoas ativas nos boxes');
assert.equal(w.capacityHH,430.5,'quatro descansos reduzem a capacidade por gargalo de equipe');
state.team[1].restAt=state.tick;
w=weekly.calculate(state,data);
assert.equal(w.ticks[0].grossHH,10.5,'cinco descansos: um funcionário ativo');
assert.equal(w.ticks[1].grossHH,31.5,'descanso do turno atual não é projetado a turnos futuros');
assert.equal(w.capacityHH,420,'cinco descansos reduzem capacidade do turno em 21 HH');
rested.restAt=null;
state.team[1].restAt=null;
state.team.slice(3).forEach(m=>m.restAt=null);
state.shift=1;
w=weekly.calculate(state,data);
assert.equal(w.ticks[0].shift,'B');
assert.equal(w.ticks[1].shift,'A');
assert.equal(w.ticks[1].day,2,'mapeamento de dias corrige turno B inicial');
assert.equal(w.ticks[13].shift,'A','14 turnos começando em B terminam em A');
assert.equal(w.fixedWageReference,7*(state.team.length*220+180),'sete viradas de dia também começando em B');
const first=state.jobs[0],scenario=engine.scenario(data,first.scene);
first.stage=6;first.materialUsed=false;
state.stock[scenario.material]=0;
state.orders.push({id:'PC001',item:scenario.material,qty:1,eta:state.tick+1});
w=weekly.calculate(state,data);
assert.equal(w.materials.length,1,'apenas o diagnóstico concluído entra no mapa de peças');
assert.equal(w.materials[0].demand,1);
assert.equal(w.materials[0].gapNow,1,'falta de peça agora');
assert.equal(w.materials[0].ordered,1,'pedido previsto dentro do horizonte');
assert.equal(w.materials[0].gapAfterKnownReceipts,0,'recebimento conhecido poderia cobrir necessidade; não garante reserva');
assert.equal(w.ticks[0].receiptCount,1,'pedido chega no fim do turno atual');
assert.equal(w.ticks[0].receipts[0].id,'PC001');
assert.equal(state.stock[scenario.material],0,'consulta não antecipa recebimento');
const second=state.jobs[1];
second.stage=6;
const secondScenario=engine.scenario(data,second.scene);
if(secondScenario.material===scenario.material){
 w=weekly.calculate(state,data);
 assert.equal(w.materials[0].demand,2,'duas OS disputando mesmo material contam duas necessidades');
 assert.equal(w.materials[0].gapAfterKnownReceipts,1,'pedido unitário não resolve duas faltas');
}else{
 w=weekly.calculate(state,data);
 assert.equal(w.materials.length,2,'materiais distintos aparecem separadamente');
}
state.orders.push({id:'PC002',item:scenario.material,qty:1,eta:state.tick+16});
w=weekly.calculate(state,data);
assert.equal(w.receiptCount,1,'pedido após horizonte não é contado como entrega semanal');
assert.equal(w.materials.find(x=>x.id===scenario.material).ordered,1,'pedido além de 14 turnos não reduz déficit na janela');
const before=JSON.stringify(state);
w=weekly.calculate(state,data);
assert.equal(JSON.stringify(state),before,'leituras repetidas são imutáveis');
const html=fs.readFileSync(path.join(root,'phaser-play/index.html'),'utf8');
const game=fs.readFileSync(path.join(root,'phaser-play/game.js'),'utf8');
assert.ok(html.includes('weekly.js?v=0.7.9'),'módulo carregado no Pages');
assert.ok(html.includes('game.js?v=0.8.17'),'JS principal versionado');
assert.ok(html.includes('weeklyScroll'),'layout horizontal responsivo presente');
assert.ok(game.includes("function drawWeekly()"),'quadro semanal implementado');
assert.ok(game.includes("planningHorizon='turn'"),'aba por padrão mantém planejamento do próximo turno');
assert.ok(game.includes('data-planning-horizon="week"'),'controle explícito de horizonte');
assert.ok(game.includes('PORCARIA_WEEKLY.calculate(state,data)'),'consulta dados atuais sem modificar estado');
assert.ok(!game.includes('window.PORCARIA_WEEKLY.advance'),'visão semanal não modifica a simulação');
console.log('OK: 14 turnos, HH brutas, diagnóstico separado, descanso, ETA, materiais e imutabilidade.');
