'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const M=require('../phaser-play/assembly-sequence.js');
const PIN=require('../phaser-play/assembly-pin-impact.js');
const html=fs.readFileSync('phaser-play/assembly-workbench.html','utf8');
const game=fs.readFileSync('phaser-play/game.js','utf8');
const index=fs.readFileSync('phaser-play/index.html','utf8');
let s=M.create();
assert.equal(PIN.canStrike(s),false,'pino escondido não pode receber golpe');
assert.equal(PIN.strike(s,300).ok,false);
for(const id of ['removeBolt:g1','removeBolt:g2','removePart:guard','removeBolt:l1','removeBolt:l2','removePart:leftPad','removePart:leftRetainer','removeBolt:r1','removeBolt:r2','removePart:rightPad','removePart:rightRetainer'])
 assert.equal(M.apply(s,id).ok,true,id);
assert.equal(PIN.canStrike(s),true,'liberou o acesso ao pino');
assert.equal(M.apply(s,'removePart:pin').ok,false,'não retira pino sem três golpes');
const targets=PIN.targets;
for(let i=0;i<3;i++){
 const t=targets[i];
 const time=(Math.asin(2*t-1))*460;
 const stroke=PIN.strike(s,time);
 assert.equal(stroke.round,i+1);
 assert.equal(stroke.precise,true);
 assert.equal(stroke.hits,i+1);
 assert.equal(PIN.isValid(s),true);
 if(i<2)assert.equal(M.apply(s,'removePart:pin').ok,false);
}
assert.equal(PIN.status(s).finished,true);
assert.equal(PIN.strike(s,200).ok,false,'3 impactos, sem repetição');
assert.equal(M.apply(s,'removePart:pin').ok,true);
assert.equal(s.installed.pin,false);
assert.equal(s.pinImpact.hits,3);
assert.equal(M.apply(s,'removePart:bushing').ok,true);
assert.equal(M.apply(s,'inspect').ok,true);
assert.equal(M.apply(s,'installPart:bushing').ok,true);
assert.equal(M.apply(s,'installPart:pin').ok,true,'remontagem não exige marretar outra vez');
assert.ok(html.includes('data-strike-pin'),'marreta deve estar no blueprint');
assert.ok(html.includes('id="impactMini"')&&html.includes('impactCursor'));
assert.ok(html.includes("PIN.strike(s,now-impactAnchor)"),'pontuação ligada ao motor interno');
assert.ok(html.includes("doAction('removePart:pin'"),'marreta desbloqueia a peça real');
assert.ok(html.includes('porcaria:assembly:complete'),'comunicação restrita com campanha');
assert.ok(html.includes("params.get('mode')==='campaign'"),'chave de save por OS e turno');
assert.ok(game.includes('repairAssistBlueprintFrame'),'OS incorpora a bancada');
assert.ok(game.includes("ev.origin!==window.location.origin"),'validar origem da mensagem');
assert.ok(game.includes("ev.source!==session.frame?.contentWindow"),'validar frame da OS');
assert.ok(game.includes("!Number.isInteger(m.hits)"),'validar pontuação no retorno');
assert.ok(game.includes("REPAIR.finish(state,E,session.id,m.hits)"),'manter bônus legado');
assert.ok(game.includes("if(kind!=='hammer')"),'torque independente desativado');
assert.ok(index.includes('repairAssistBlueprintFrame'),'painel acessível no navegador');
const snippets=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(x=>x[1]).filter(Boolean);
assert.equal(snippets.length,1);
new vm.Script(snippets[0],{filename:'integrated-workbench.js'});
console.log('Ciclo 42.4: pino exige três golpes, montagem compatível, resultado seguro para OS.');
