/* P.O.R.C.A.R.I.A. — briefing do turno: testes de lógica sem navegador. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const E=require(path.join(root,'engine.js'));
const B=require(path.join(root,'phaser-play','shift-brief.js'));
const data=JSON.parse(fs.readFileSync(path.join(root,'game-data.json'),'utf8'));
const s=E.create(data,()=>0.42);
const original=JSON.stringify(s);
let b=B.compute(s,data);
assert.equal(JSON.stringify(s),original,'consultar briefing não pode alterar save');
assert.equal(b.counts.assigned,0,'no início não há OS alocadas');
assert.equal(b.counts.free,3,'os três boxes começam livres');
assert.equal(b.bays.length,3,'sempre exibir três boxes');
assert.equal(b.payroll,0,'no turno A não há virada de dia');
assert.ok(b.unattendedCritical.every(j=>j.id),'OS crítica sem alocação é explicitada');
const j=s.jobs[0],m=s.team[0],sc=E.scenario(data,j.scene);
assert.equal(E.attach(s,j.id,m.id,1,true),null,'alocação de OS simulada');
s.tools[sc.tool]=true;
b=B.compute(s,data);
assert.equal(b.bays[1].kind,'diagnose','ferramenta pronta permite diagnóstico');
assert.equal(b.bays[1].stage,0,'etapas refletidas no preview');
assert.equal(b.counts.assigned,1);
assert.equal(b.counts.diagnosis,1);
assert.equal(b.counts.free,2);
s.tools[sc.tool]=false;
b=B.compute(s,data);
assert.equal(b.bays[1].kind,'tool','falta de ferramental impede até o diagnóstico');
assert.equal(b.bays[1].neededTool,sc.tool);
assert.equal(b.counts.blocked,1);
s.tools[sc.tool]=true;
j.stage=6;j.materialUsed=false;s.stock[sc.material]=0;
b=B.compute(s,data);
assert.equal(b.bays[1].kind,'material','sem peça depois do diagnóstico: bloqueio');
assert.equal(b.bays[1].neededMaterial,sc.material);
s.orders.push({id:'PC777',item:sc.material,qty:2,eta:s.tick+1});
const beforeReceipt=JSON.stringify(s);
b=B.compute(s,data);
assert.equal(JSON.stringify(s),beforeReceipt,'prévia não deve registrar recebimento antecipado');
assert.equal(b.bays[1].kind,'material','pedido com ETA ao final do turno não desbloqueia o reparo');
assert.equal(b.deliveries.length,1,'pedido é mostrado na logística de encerramento');
assert.ok(b.deliveryNote.includes('fim do turno'),'aviso não promete entrega antes do trabalho');
s.stock[sc.material]=1;
b=B.compute(s,data);
assert.equal(b.bays[1].kind,'repair','material em saldo torna reparo apto');
s.stock[sc.material]=0;j.materialUsed=true;
b=B.compute(s,data);
assert.equal(b.bays[1].kind,'repair','material reservado permite continuar reparo sem saldo');
m.physical=20;
b=B.compute(s,data);
assert.equal(b.fatigue.length,1,'fadiga aparece sem bloquear automaticamente');
assert.equal(b.bays[1].fatigued,true);
s.shift=1;
b=B.compute(s,data);
assert.equal(b.payroll,s.team.length*220+180,'virada do dia calcula somente folha fixa conhecida');
assert.equal(b.nextShift,'A','turno B retorna ao A');
assert.equal(b.deterministic,false,'sem promessa de conclusão determinística');
const ui=fs.readFileSync(path.join(root,'phaser-play','index.html'),'utf8');
const js=fs.readFileSync(path.join(root,'phaser-play','game.js'),'utf8');
assert.equal((ui.match(/id="shiftBrief"/g)||[]).length,1,'painel de briefing único');
assert.ok(ui.includes('data-panel="shift"'),'briefing integrado ao modal principal');
assert.ok(ui.includes('shift-brief.js?v=0.7.7'),'módulo de prévia versionado na publicação');
assert.ok(js.includes('PORCARIA_SHIFT_BRIEF.compute(state,data)'),'jogo usa a leitura pura dos bloqueios');
assert.ok(js.includes("$('advance').addEventListener('click',()=>openPanel('shift'))"),'botão abre prévia sem simular o turno');
assert.ok(js.includes("dataset.shiftAction==='confirm'"),'execução depende de confirmação explícita');
assert.ok(js.includes("dataset.shiftAction==='cancel'"),'cancelamento não modifica o turno');
assert.ok(js.includes("Number(shiftAction.dataset.turnTick)!==state.tick"),'briefing expira quando o turno muda');
assert.ok(!js.includes('AVANÇAR 8 HORAS?'),'confirm nativo substituído pelo modal integrado');
assert.ok(js.includes('data-shift-stock'),'atalho de recurso indisponível abre almoxarifado');
console.log('OK: briefing pré-turno, estoque, ferramental, ETA, fadiga, folha e ações da UI.');
