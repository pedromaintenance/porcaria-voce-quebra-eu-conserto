/* Ciclo 16 — Diva e OS preventivas automáticas: regressão de engenharia e sprites. */
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const D=require('../game-data.json'),E=require('../engine.js');
const PM=require('../phaser-play/preventive-orders.js');
const F=require('../phaser-play/fleet-telemetry.js');
assert.equal(PM.VERSION,'16.0.0');
const make=()=>E.create(D,()=>0.42);
const s=make(),all=[...s.jobs,...s.preventiveOrders];
assert.ok(s.preventiveOrders.length>=1,'campanha inicia com pelo menos uma OS de preventiva vencida');
assert.equal(new Set(all.map(x=>x.id)).size,all.length,'numeração de OS compartilhada sem colisão');
assert.equal(s.preventiveOrders.every(x=>x.kind==='preventive'&&x.createdAutomatically&&x.supervisor==='Diva'),true);
assert.ok(s.preventiveOrders.every(x=>x.status==='open'&&x.assigned===null));
assert.ok(s.preventiveOrders.every(x=>!s.jobs.some(j=>j.asset===x.asset)),'preventiva não nasce em ativo com corretiva');
const pending=s.preventiveOrders[0],mechanic=s.team[0];
const cash=s.cash,starts=JSON.stringify(s);
assert.equal(PM.compute(s,D).open,s.preventiveOrders.length);
assert.equal(JSON.stringify(s),starts,'consultar carteira não altera save');
assert.equal(E.generatePreventiveOrders(s,D),0,'geração idempotente sem duplicar OS');
assert.equal(s.cash,cash,'geração não desconta caixa');
assert.equal(E.assignPreventiveOrder(s,D,pending.id,'inexistente',0),'Mecânico não encontrado.');
assert.equal(E.assignPreventiveOrder(s,D,pending.id,mechanic.id,9),'Box inválido.');
assert.equal(E.assignPreventiveOrder(s,D,pending.id,mechanic.id,0),null);
assert.equal(pending.status,'in_progress');
assert.equal(pending.bay,0);
assert.equal(mechanic.assigned,pending.id);
assert.equal(s.decisionHistory.some(x=>x.type==='preventive_os_generated'),false,'OS iniciais não são decisões do jogador');
assert.ok(s.decisionHistory.some(x=>x.type==='preventive_os_assigned'));
assert.ok(E.attach(s,s.jobs[0].id,mechanic.id,1,false)?.includes('alocado'));
assert.ok(E.attach(s,s.jobs[0].id,s.team[1].id,0,false)?.includes('preventiva'));
const other=s.preventiveOrders.find(x=>x.id!==pending.id);
if(other)assert.ok(E.assignPreventiveOrder(s,D,other.id,s.team[1].id,0)?.includes('Box'));
assert.equal(E.releasePreventiveOrder(s,pending.id),null);
assert.equal(mechanic.assigned,null);
assert.equal(pending.status,'open');
assert.equal(E.assignPreventiveOrder(s,D,pending.id,mechanic.id,0),null);
const plan=PM.compute(s,D);
assert.equal(plan.allocated,1);
assert.equal(plan.orders.find(r=>r.id===pending.id).mechanic,mechanic.name);
const res=E.advance(s,D,()=>0.95);
assert.ok(res.hours>=pending.hours,'HH produtivas incluem preventiva');
assert.equal(pending.status,'completed');
assert.equal(pending.assigned,null);
assert.equal(pending.bay,null);
assert.equal(mechanic.assigned,null);
assert.equal(s.cash,cash-pending.cost,'custo reconhecido ao executar');
assert.equal(s.preventiveJobs.filter(x=>x.orderId===pending.id&&x.status==='completed').length,1);
assert.equal(s.preventiveEffects.some(x=>x.asset===pending.asset),true);
assert.equal(s.preventiveDue[pending.asset],
 s.fleetTelemetry.assets[pending.asset].hourmeter+PM.INTERVAL,'vencimento baseado no horímetro após avanço do turno');
const sample=s.fleetTelemetry.samples.at(-1),assetRow=sample.perAsset.find(x=>x.asset===pending.asset);
assert.equal(assetRow.preventive,pending.hours,'parada contabilizada por horas preventivas efetivamente executadas');
assert.equal(assetRow.operating+assetRow.standby+assetRow.corrective+assetRow.preventive,12);
assert.ok(s.decisionHistory.some(x=>x.type==='preventive_os_completed'));
assert.equal(E.validate(JSON.parse(JSON.stringify(s))),true);
const failing=make(),p=failing.preventiveOrders[0];failing.cash=0;
assert.ok(E.assignPreventiveOrder(failing,D,p.id,failing.team[0].id,0)?.includes('Caixa'));
assert.equal(p.status,'open');assert.equal(p.worked,0);
const old=make();
delete old.preventiveOrders;delete old.preventiveDue;
old.tick=15;old.day=8;old.shift=0;
E.generatePreventiveOrders(old,D);
assert.equal(old.preventiveOrders.every(x=>x.dueHourmeter>=old.fleetTelemetry.assets[x.asset].hourmeter),true);
assert.equal(E.validate(old),true);
const buf=fs.readFileSync('phaser-play/assets/characters/diva-4poses.webp');
assert.equal(buf.toString('ascii',0,4),'RIFF');
assert.equal(buf.toString('ascii',8,12),'WEBP');
assert.equal(buf.toString('ascii',12,16),'VP8X');
const width=1+buf.readUIntLE(24,3),height=1+buf.readUIntLE(27,3);
assert.deepEqual([width,height],[580,622],'spritesheet deve ser 2×2 com quadros 290×311');
const ui=fs.readFileSync('phaser-play/game.js','utf8');
const sw=fs.readFileSync('sw.js','utf8'),html=fs.readFileSync('phaser-play/index.html','utf8');
assert.ok(ui.includes("diva:'./assets/characters/diva-4poses.webp'"));
assert.ok(ui.includes("name==='diva'?WORKER_RENDER_FRAME.width"));
assert.ok(ui.includes("person==='diva'?WORKER_RENDER_FRAME"));
assert.ok(ui.includes("await import('./preventive-orders.js?v=0.9.19')"));
assert.ok(ui.includes("const supervisor=this.worker("));
assert.ok(ui.includes("data-pm-os-assign"));
assert.ok(ui.includes("data-pm-os-release"));
assert.ok(ui.includes("const isPM=j?.kind==='preventive'"));
assert.ok(sw.includes("diva0919")&&sw.includes("'./phaser-play/assets/characters/diva-4poses.webp'"));
assert.ok(sw.includes("'./phaser-play/preventive-orders.js'"));
assert.ok(html.includes('game.js?v='));
console.log('OK ciclo 16: OS automáticas por horímetro, Diva em box, HH/custo, concorrência, saves, 4 poses e PWA.');
