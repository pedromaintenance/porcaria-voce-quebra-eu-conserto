/* Ciclo 11 — testes de programação PCM: sem automação e sem spoilers. */
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const E=require('../engine.js'),D=require('../game-data.json'),S=require('../phaser-play/weekly-schedule.js');
assert.equal(S.VERSION,'19.0.0');
assert.equal(D.scenarios.length,124);
const fresh=()=>E.create(D,()=>0.47);
const s=fresh(),j=s.jobs[0],k=s.jobs[1],m=s.team[0],n=s.team[1];
for(const job of s.jobs)s.tools[E.scenario(D,job.scene).tool]=true;
const initial=JSON.stringify(s);
let report=S.compute(s,D);
assert.equal(report.slots.length,14);
assert.equal(report.pending,0);
assert.equal(JSON.stringify(s),initial,'a consulta do cronograma não pode alterar o save');
assert.equal(E.scheduleJob(s,D,j.id,m.id,0,s.tick+1),null);
assert.equal(s.scheduleEntries[0].status,'planned');
assert.equal(s.scheduleEntries[0].tick,s.tick+1);
assert.ok(E.scheduleJob(s,D,j.id,n.id,1,s.tick+2).includes('já programada'));
assert.ok(E.scheduleJob(s,D,k.id,m.id,1,s.tick+1).includes('Conflito'));
assert.ok(E.scheduleJob(s,D,k.id,n.id,0,s.tick+1).includes('Conflito'));
assert.equal(E.scheduleJob(s,D,k.id,n.id,1,s.tick+1),null,'um segundo box e mecânico no mesmo turno é possível');
assert.equal(S.compute(s,D).pending,2);
assert.equal(S.compute(s,D).slots[1].reserved,2);
assert.equal(S.compute(s,D).slots[1].free,1);
assert.equal(s.jobs.find(x=>x.id===j.id).assigned,null,'reserva não atribui a OS automaticamente');
assert.ok(s.decisionHistory.filter(x=>x.type==='schedule_created').length===2);
const other=s.jobs[2];
assert.ok(E.scheduleJob(s,D,other.id,n.id,2,s.tick+1).includes('Conflito'));
assert.equal(E.cancelSchedule(s,s.scheduleEntries[1].id),null);
assert.equal(s.scheduleEntries[1].status,'cancelled');
assert.equal(E.scheduleJob(s,D,other.id,n.id,2,s.tick+1),null,'cancelamento libera recurso');
assert.equal(E.cancelSchedule(s,s.scheduleEntries[1].id),'Programação ativa não encontrada.');
// Próximo turno: reservar mecânico e box interfere na alocação manual concorrente.
E.advance(s,D,()=>0.8);
assert.equal(s.tick,1);
assert.ok(E.attach(s,k.id,m.id,2,false).includes('reservado'));
assert.ok(E.attach(s,k.id,n.id,0,false).includes('reservado'));
assert.equal(E.attach(s,j.id,m.id,0,true),null);
assert.equal(s.scheduleEntries[0].status,'fulfilled','reserva cumprida somente após alocação explícita');
assert.ok(s.decisionHistory.some(x=>x.type==='schedule_fulfilled'));
assert.equal(S.compute(s,D).fulfilled,1);
const legacy=fresh();delete legacy.scheduleEntries;delete legacy.nextSchedule;
assert.equal(E.validate(legacy),true,'save legado permanece válido');
const a=legacy.jobs[0],sc=E.scenario(D,a.scene);
legacy.tools[sc.tool]=true;a.stage=6;a.materialUsed=false;legacy.stock[sc.material]=0;
assert.ok(E.scheduleJob(legacy,D,a.id,legacy.team[0].id,0,legacy.tick+2).includes('Peça'));
legacy.orders.push({id:'P1',item:sc.material,qty:1,eta:legacy.tick+2});
assert.equal(E.scheduleJob(legacy,D,a.id,legacy.team[0].id,0,legacy.tick+2),null);
assert.equal(legacy.stock[sc.material],0,'ETA não altera saldo atual');
const b=legacy.jobs[1];
const otherSc=E.scenario(D,b.scene);
legacy.tools[otherSc.tool]=true;b.stage=6;b.materialUsed=false;
if(otherSc.material===sc.material)assert.ok(E.scheduleJob(legacy,D,b.id,legacy.team[1].id,1,legacy.tick+2).includes('Peça'),'duas reservas disputando um item');
assert.equal(E.validate(JSON.parse(JSON.stringify(legacy))),true);
const pending=fresh();const jp=pending.jobs[0],sp=E.scenario(D,jp.scene);
pending.tools[sp.tool]=true;
assert.equal(E.scheduleJob(pending,D,jp.id,pending.team[0].id,0,pending.tick),null);
assert.ok(E.attach(pending,jp.id,pending.team[1].id,1,false).includes('reserva'));
const open=JSON.stringify(pending),pre=S.compute(pending,D);
assert.ok(pre.rows[0].availability.includes('não revelada'),'não expor material antes do diagnóstico');
assert.equal(JSON.stringify(pending),open);
E.advance(pending,D,()=>0.8);
assert.equal(pending.scheduleEntries[0].status,'missed','compromisso sem ação passou do turno');
assert.ok(pending.decisionHistory.some(x=>x.type==='schedule_missed'));
const ui=fs.readFileSync('phaser-play/game.js','utf8'),html=fs.readFileSync('phaser-play/index.html','utf8'),sw=fs.readFileSync('sw.js','utf8');
assert.ok(ui.includes("await import('./weekly-schedule.js?v=0.9.14')"));
assert.ok(ui.includes('function drawSchedule()')&&ui.includes('data-schedule-book')&&ui.includes('data-schedule-start'));
assert.ok(html.includes('game.js?v='),'versão legada compatível com testes anteriores');
assert.ok(sw.includes('c11-scheduling')&&sw.includes("'./phaser-play/weekly-schedule.js'"));
console.log('OK: Ciclo 11 — 14 turnos, reserva, conflito, execução manual, materiais, auditoria e saves.');
