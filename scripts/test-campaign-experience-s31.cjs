/* Sprint 31 · provas puras de campanha híbrida e personagens. */
'use strict';
const assert=require('node:assert/strict');
const E=require('../engine.js');
const D=require('../game-data.json');
const C=require('../phaser-play/campaign-experience-s31.js');
const s=E.create(D,()=>.42);
assert.equal(C.goals(s).length,3);
assert.ok(C.goals(s).every(x=>!x.done));
assert.equal(C.summary(s).complete,false);
assert.match(C.renderGoals(s),/metas opcionais/);
assert.match(C.renderGoals(s),/nenhuma delas restringe/i);
s.jobs.push({id:'OSCRITICAL',asset:'EQ01·06',priority:3,openedTick:s.tick,status:'fila'});
const radio=C.cue(s,'queue');
assert.equal(radio.by,'Elton · Rádio');
assert.ok(!radio.text.includes('raiz'));
assert.equal(C.dismiss(s,radio.key),true);
assert.equal(C.cue(s,'queue'),null);
assert.equal(C.dismiss(s,radio.key),true);
assert.equal(s.guideDismissed.length,1);
assert.deepEqual(JSON.parse(JSON.stringify(s)).guideDismissed,s.guideDismissed);
s.inspections.push({id:'IN105',tick:s.tick,asset:'EQ07·03',status:'finding'});
assert.equal(C.cue(s,'inspection').by,'Nemuel · Inspeções');
s.notifications.push({id:'NM555',status:'aprovada_pcm',origin:'inspecao_sensitiva_simulada',openedTick:s.tick});
s.preventiveMetrics.executed=1;
s.done.push({id:'OSFINISHED'});
assert.ok(C.goals(s).every(x=>x.done));
s.day=21;s.closed=true;
const end=C.summary(s);
assert.equal(end.finished,3);
assert.equal(end.complete,true);
assert.match(C.renderGoals(s),/RELATÓRIO DO CICLO/);
assert.match(C.renderGoals(s),/modo livre permanece disponível/i);
s.notifications.push({id:'NM556',monitorOnly:true,asset:'EQ01·02',status:'monitorando',openedTick:s.tick});
assert.equal(C.cue(s,'monitoring').by,'Pedro · Monitoramento');
s.training={offers:[{id:'E42'}]};
assert.equal(C.cue(s,'training').by,'Bia · Treinamentos');
assert.equal(C.renderCue(s,'training').includes('data-campaign-dismiss'),true);
console.log('OK S31-05: metas opcionais, marco de 21 dias, persistência de dispensa, 4 personagens e ausência de bloqueio.');
