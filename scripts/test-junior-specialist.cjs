'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.join(__dirname,'..');
const dir=path.join(root,'phaser-play/assets/characters/junior');
const manifest=JSON.parse(fs.readFileSync(path.join(dir,'manifest.json'),'utf8'));
const E=require(path.join(root,'engine.js'));
const data=JSON.parse(fs.readFileSync(path.join(root,'game-data.json'),'utf8'));
const fresh=E.create(data,()=>0.43);
assert.equal(fresh.team.length,7,'sete integrantes iniciais');
const junior=fresh.team.find(m=>m.name==='Junior');
assert.ok(junior,'Junior integrante inicial');
assert.equal(junior.id,'M7');
assert.equal(junior.specialty,'Especialista');
assert.equal(junior.role,'geral','especialista é título, sem inventar disciplina');
assert.equal(junior.sprite,'junior','campo usa balaclava');
assert.equal(junior.trainingSprite,'junior-training','treinamento usa camisa azul');
assert.equal(fresh.nextPerson,8);
const unchanged=JSON.stringify(fresh);
E.normalizeRoster(fresh);
assert.equal(JSON.stringify(fresh),unchanged,'migração idempotente');
assert.equal(E.hire(fresh,()=>0.4),null);
assert.equal(fresh.team[7].name,'Mecânico');
assert.equal(fresh.team[7].sprite,null);
assert.equal(fresh.team[7].id,'M8');
// Campanha anterior com M7 contratado: não reatribuir ID e não apagar sua OS.
const legacy=E.create(data,()=>0.4);
legacy.team=legacy.team.slice(0,6);
const oldJob=legacy.jobs[0];
legacy.team.push({id:'M7',name:'Mecânico',avatar:'🔧',role:'rodante',specialty:'Mecânico',sprite:null,skill:89,physical:82,mental:83,morale:91,assigned:oldJob.id});
oldJob.assigned='M7';oldJob.bay=0;legacy.nextPerson=8;
E.normalizeRoster(legacy);
const generic=legacy.team.find(m=>m.id==='M7');
assert.equal(generic.name,'Mecânico');
assert.equal(generic.skill,89);
assert.equal(generic.role,'rodante');
assert.equal(oldJob.assigned,'M7');
assert.equal(legacy.team.find(m=>m.name==='Junior').id,'M8','não reciclar M7');
const snapshot=JSON.stringify(legacy);
E.normalizeRoster(legacy);assert.equal(JSON.stringify(legacy),snapshot);
assert.equal(manifest.characterId,'junior');
assert.equal(manifest.field.purpose,'oficina-OS');
assert.ok(manifest.training.purpose.includes('treinamento'));
for(const key of ['field','training']){
 const item=manifest[key],bytes=fs.readFileSync(path.join(dir,item.file));
 assert.equal(bytes.length,item.bytes,key+' completo');
 assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'),item.sha256);
 assert.equal(bytes.toString('ascii',0,4),'RIFF');assert.equal(bytes.toString('ascii',8,12),'WEBP');
 assert.equal(bytes.toString('ascii',12,16),'VP8X');
 assert.ok((bytes[20]&0x10)!==0,key+' com transparência');
 assert.equal(1+bytes[24]+(bytes[25]<<8)+(bytes[26]<<16),1160);
 assert.equal(1+bytes[27]+(bytes[28]<<8)+(bytes[29]<<16),1244);
 assert.equal(item.frames.length,4);
}
const g=fs.readFileSync(path.join(root,'phaser-play/game.js'),'utf8');
const html=fs.readFileSync(path.join(root,'phaser-play/index.html'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
assert.ok(g.includes("junior:'./assets/characters/junior/junior-work-4poses.webp'"));
assert.ok(g.includes("const TEAM_PORTRAITS=Object.freeze({junior:'./assets/characters/junior/junior-training-4poses.webp'})"));
assert.ok(g.includes("const texture=person&&WORKER_SHEETS[person]?'worker_'+person:null"));
assert.ok(g.includes('TEAM_PORTRAITS[m.sprite]||WORKER_SHEETS[m.sprite]'));
assert.ok(!g.includes("this.load.spritesheet('junior-training'"),'sem carregar uniforme azul como campo');
assert.ok(html.includes('game.js?v=0.8.18'));
assert.ok(sw.includes('porcaria-vqec-20261017-v098'));
for(const key of ['field','training'])assert.ok(sw.includes(manifest[key].file));
assert.equal(manifest.state.trainingModuleImplemented,false);
assert.equal(manifest.state.balanceBonusImplemented,false);
console.log('OK: Junior, 8 poses, trabalho balaclava, treino azul, M7 legado preservado, cache e integridade.');
