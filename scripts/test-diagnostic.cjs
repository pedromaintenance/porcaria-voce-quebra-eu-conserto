/* Testes diagnósticos: autoria, privacidade das respostas, continuidade e legado. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'..');
const E=require(path.join(root,'engine.js'));
const Board=require(path.join(root,'phaser-play','diagnostic-board.js'));
const View=require(path.join(root,'phaser-play','diagnostic-view.js'));
const data=JSON.parse(fs.readFileSync(path.join(root,'game-data.json'),'utf8'));
const s=E.create(data,()=>0.42);
const j=s.jobs[0],sc=E.scenario(data,j.scene),m=s.team[0];
let report=Board.compute(s,data,j);
assert.equal(report.currentLabel,'Sistema');
assert.equal(report.stage,0);
assert.equal(report.progress,0);
assert.equal(report.steps.length,6);
assert.ok(report.steps.every(step=>step.result===null),'nenhuma resposta pendente é mostrada');
assert.equal(report.log.length,0);
assert.equal(report.player.length,0);
assert.equal(report.mechanic.length,0);
assert.equal(E.attach(s,j.id,m.id,0,true),null);
s.tools[sc.tool]=true;
const first=j.options[0].find(x=>x.id!==sc.path[0]);
assert.ok(first,'hipótese incorreta disponível');
let reply=E.answer(s,data,j.id,first.id);
assert.equal(reply.ok,false);assert.equal(j.stage,0);
report=Board.compute(s,data,j);
assert.equal(report.wrongCount,1);
assert.equal(report.log[0].kind,'rejected');
assert.equal(report.log[0].value,first.label);
assert.ok(report.steps.every(x=>x.result===null),'erro não revela a resposta certa');
reply=E.answer(s,data,j.id,sc.path[0]);
assert.equal(reply.ok,true);
assert.equal(j.stage,1);
report=Board.compute(s,data,j);
assert.equal(report.player.length,1);
assert.equal(report.player[0].source,'player');
assert.equal(report.steps[0].result,report.player[0].result);
assert.equal(report.steps[1].result,null);
assert.equal(report.currentLabel,'Grupo');
assert.equal(report.progress,17);
assert.equal(report.log[1].mechanicName,m.name);
assert.equal(E.hint(s,data,j.id),null);
report=Board.compute(s,data,j);
assert.ok(report.hasHint);
assert.ok(report.clue);
assert.ok(report.log.some(e=>e.kind==='evidence'&&e.source==='player'));
const before=JSON.stringify(s),firstReport=JSON.stringify(report);
assert.equal(JSON.stringify(Board.compute(s,data,j)),firstReport,'leitura determinística');
assert.equal(JSON.stringify(s),before,'leitura não muta estado');
E.advance(s,data,()=>0); // turno automático com sucesso do mecânico
report=Board.compute(s,data,j);
assert.ok(report.mechanic.length>=1,'descoberta do mecânico registrada no avanço');
assert.equal(report.mechanic[0].mechanicName,m.name);
assert.equal(report.player.length,1,'autoria do jogador não confundida com automático');
assert.equal(report.stage,2);
assert.equal(report.steps[2].result,null);
const rendered=View.render(report,j.id);
assert.ok(rendered.includes('ETAPA 3 DE 6 · SUBGRUPO'),'fase atual destacada');
assert.ok(rendered.includes('VOCÊ CONFIRMOU'));
assert.ok(rendered.includes('MECÂNICO DESCOBRIU'));
assert.ok(rendered.includes('REGISTRO DA INVESTIGAÇÃO'));
assert.ok(rendered.includes('role="progressbar"'));
assert.ok(!rendered.includes('diagnosticAnswer'),'visualização não responde à etapa pendente');
// Save antigo confirma prefixo, mas não deve inventar quem respondeu.
const legacy={...j,stage:4,diagnosticLog:undefined,hints:{}};
const l=Board.compute(s,data,legacy);
assert.equal(l.unknown.length,4);
assert.equal(l.player.length,0);assert.equal(l.mechanic.length,0);
assert.equal(l.steps[4].result,null);
assert.ok(l.log.every(e=>e.legacy&&e.source==='unknown'));
assert.ok(View.render(l,j.id).includes('HISTÓRICO ANTERIOR'));
// Injeção de texto do save não pode criar HTML arbitrário.
const malicious={...report,assignedMechanic:'<img src=x onerror=alert(1)>'};
assert.ok(View.render(malicious,j.id).includes('&lt;img src=x'));
assert.ok(!View.render(malicious,j.id).includes('<img src=x'));
const done={...j,stage:6};
const full=Board.compute(s,data,done);
assert.equal(full.progress,100);assert.equal(full.complete,true);
assert.equal(full.currentIndex,null);
assert.ok(full.steps.every(x=>x.status==='confirmed'));
const game=fs.readFileSync(path.join(root,'phaser-play','game.js'),'utf8');
const html=fs.readFileSync(path.join(root,'phaser-play','index.html'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
assert.ok(game.includes('PORCARIA_DIAGNOSTIC_VIEW.render(window.PORCARIA_DIAGNOSTIC.compute(state,data,j),j.id)'));
assert.ok(html.includes('diagnostic-board.js?v=0.8.8')&&html.includes('diagnostic-view.js?v=0.8.8'));
assert.ok(html.includes('game.js?v=0.8.21'));
assert.ok(html.includes('.diagnosticStep.current')&&html.includes('.diagnosticGroups'));
assert.ok(sw.includes("'./phaser-play/diagnostic-board.js'"));
assert.ok(sw.includes("'./phaser-play/diagnostic-view.js'"));
console.log('OK: seis etapas, acertos, descobertas mecânico, evidências, hipóteses rejeitadas, saves antigos, antisspoiler, XSS e UI.');
